#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Emit a corpus manifest for the F39 (D-6) local fuzz campaign.

Records WHAT the campaign's corpus contained rather than committing 44 binary
fuzzer artifacts into the docs tree: name, size and sha256 per unit, plus the
seed/grown split. That is enough to reproduce the "corpus growth" claim and to
tell later whether a re-run reached the same place, without adding a binary
corpus to a repository where ``core.autocrlf=true`` makes committed binaries a
standing hazard.

Usage:
    python tools/gate/phase39_corpus_manifest.py \
        --seeds  build-fuzz-local/fuzz/seeds_b \
        --corpus build-fuzz-local/fuzz/corpus_b \
        --out    docs/audit/meta-audit-2026-07/followup/phase-39/corpus-manifest.md
"""

from __future__ import annotations

import argparse
import hashlib
import io
import sys
from pathlib import Path


def digest(path: Path) -> tuple[int, str]:
    data = path.read_bytes()
    return len(data), hashlib.sha256(data).hexdigest()


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", required=True, type=Path)
    ap.add_argument("--corpus", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)

    seeds = sorted(p for p in args.seeds.iterdir() if p.is_file())
    corpus = sorted(p for p in args.corpus.iterdir() if p.is_file())

    seed_hashes = {digest(p)[1] for p in seeds}

    lines: list[str] = []
    lines.append("# F39 / D-6 — local fuzz campaign corpus manifest")
    lines.append("")
    lines.append(
        "Generated by `tools/gate/phase39_corpus_manifest.py`. The corpus units "
        "themselves are deliberately **not** committed: they are transient "
        "fuzzer output, and `core.autocrlf=true` makes committed binaries a "
        "standing corruption hazard in this repository. Name + size + sha256 is "
        "enough to substantiate the growth claim and to compare a later re-run."
    )
    lines.append("")
    lines.append(f"- seed units supplied to the campaign: **{len(seeds)}**")
    lines.append(f"- units in the working corpus afterwards: **{len(corpus)}**")
    grown = [p for p in corpus if digest(p)[1] not in seed_hashes]
    lines.append(
        f"- of which are NOT byte-identical to any supplied seed: **{len(grown)}**"
    )
    lines.append(
        "  - Note on reading that number: libFuzzer does not copy seeds into the "
        "working corpus verbatim — it stores the *reduced* unit it derived from "
        "each one. So a count equal to the corpus size does not mean every unit "
        "is a novel discovery; it means no unit survived unchanged. The honest "
        "growth figure is `stat::new_units_added` from the campaign log, quoted "
        "in the dispositions."
    )
    total = sum(digest(p)[0] for p in corpus)
    lines.append(f"- total corpus bytes: **{total}**")
    lines.append("")

    lines.append("## Seed units (committed, `tests/security/fuzz/seeds/fuzz_image_decode/`)")
    lines.append("")
    lines.append("| unit | bytes | sha256 |")
    lines.append("|---|---:|---|")
    for p in seeds:
        n, h = digest(p)
        lines.append(f"| `{p.name}` | {n} | `{h}` |")
    lines.append("")

    lines.append("## Working corpus after the campaign")
    lines.append("")
    lines.append("| unit | bytes | sha256 | origin |")
    lines.append("|---|---:|---|---|")
    for p in corpus:
        n, h = digest(p)
        origin = "seed" if h in seed_hashes else "fuzzer-generated"
        lines.append(f"| `{p.name}` | {n} | `{h}` | {origin} |")
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with io.open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {args.out} ({len(seeds)} seeds, {len(corpus)} corpus units)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
