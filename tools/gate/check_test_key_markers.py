#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Standing control: every committed PEM private key says in-file that it is
test-only.

WHAT THIS CLOSES (F1, phase-51 adversarial review)
==================================================
Phase-51 (F56) gave every generated key in `tests/fixtures/crl_chain/` a leading
`# PDFE TEST-ONLY KEY ...` marker, and `tools/gate/check_crl_chain_fixture.py`
enforces it. The stated rationale was general: an unlabelled
`-----BEGIN PRIVATE KEY` armour is indistinguishable from a real leaked key to a
secret scanner, a support bundle, or a triage engineer, and the cost of being
wrong is asymmetric -- treating a real key as test material is a breach,
treating test material as real is an afternoon.

The ENFORCEMENT, however, was scoped to a DIRECTORY (`FIXTURE_DIR`). Three
tracked, unencrypted PKCS#8 private keys sat one directory above it --
`tests/fixtures/test_tsa_key.pem`, `test_signer_ca_key.pem`, `test_ca_key.pem`
-- with no marker and no gate. So the control covered exactly the four keys that
ALSO have a byte pin in `MANIFEST.sha256` (belt and braces) and none of the
three where the marker was the only defence.

That is this project's single most recurrent defect species: the sibling one
file over. A directory-keyed control finds what is in the directory. So this
checker is keyed on FINDING KEYS instead:

  * the file set comes from `git ls-files` -- TRACKED files only. A filesystem
    walk would sweep up build trees, vcpkg, and untracked scratch keys a
    developer is entitled to have on disk, and would red for reasons that are
    not about the repository at all.
  * a file is in scope when it contains a real PEM private-key BLOCK: a BEGIN
    armour, a base64 body, and the MATCHING END armour. Requiring the whole
    block is what keeps prose out: a document that merely quotes the boundary
    (`docs/.../deferred-backlog.md` does, describing this very finding) has no
    body and no END, and is correctly not a key.
  * the marker must appear BEFORE the first BEGIN armour. RFC 7468 §5.2 makes
    that region ("pre-encapsulation boundary" text) something readers MUST skip,
    so a marker there is inert to every PEM parser; a marker after it lands
    inside the base64 body and corrupts the key. Reported separately, because
    the fixes differ.

NOT LIMITED TO `.pem`. Scope is decided by CONTENT, not by suffix or by
directory, so a key pasted into a `.py`, a `.cpp` string literal or a `.txt`
is in scope too. `tests/fixtures/gen_two_level_ca_signer.py` embeds eight
complete PEM keys as source literals and passes, because its `KEY_MARKER`
constant states the fact ahead of the first armour -- which is exactly the
property being asked for, in the file that actually holds the material.

CRLF NOTE
=========
`core.autocrlf=true`. `.gitattributes:98` marks `tests/fixtures/crl_chain/*.pem`
`-text` so the byte-pinned corpus travels unnormalised, but that rule does NOT
cover the three keys above -- and it deliberately need not, since nothing pins
their bytes. They will therefore arrive CRLF on a clean checkout even though
they are LF in the tree that wrote them. A comparison over raw bytes would pass
in the session that added the marker and fail after the next checkout, reporting
a checkout artefact as a missing security label. So every comparison here folds
CRLF to LF first.

Exit: 0 all checks pass; 1 a check failed; 2 usage/IO error.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

# The in-band label. Only the TOKEN is mandated, not a fixed two-line block:
# different generators name themselves differently (`gen_two_level_ca_signer.py`
# vs `generate_timestamped_pdf.py`), and a checker that demanded byte-identical
# prose would force the wrong thing to be identical. What must be present is the
# unambiguous, greppable claim.
MARKER_TOKEN = b"PDFE TEST-ONLY KEY"

# The canonical two-line form generators should emit; `{gen}` is the generator's
# repo-relative path. Advisory -- reproduced in the failure message so the fix is
# in front of whoever hits it.
MARKER_TEMPLATE = (
    "# PDFE TEST-ONLY KEY -- generated by {gen}\n"
    "# Not a secret. Never used outside the test corpus. Safe to publish.\n"
)

# A real PEM private-key block. The backreference is the point: BEGIN and END
# must name the SAME key type, which a prose mention of an armour line cannot
# satisfy. Covers `PRIVATE KEY` (PKCS#8), `RSA PRIVATE KEY` / `EC PRIVATE KEY` /
# `DSA PRIVATE KEY` (PKCS#1 and SEC1) and `ENCRYPTED PRIVATE KEY`.
# The key-type group is written to ALWAYS participate (it may match empty), so
# the `\1` backreference is a real constraint rather than an optional one: an
# `ENCRYPTED PRIVATE KEY` armour closed by a bare `END PRIVATE KEY` is not a
# block. An optional backreference would have quietly accepted that.
#
# The lines between the two armours are NOT constrained to base64. They were, in
# the first cut, and that was a hole the self-tests found: a file whose marker
# had been pasted INSIDE the body stopped matching, so it fell out of scope
# entirely and the "marker is in the wrong place" rule below could never fire on
# it -- the checker went quiet on precisely the malformed case it is meant to
# name. What is required instead is that SOME line is a real base64 body line
# (>= 16 base64 characters), which is what separates a key from prose that
# happens to quote both armour lines.
PEM_KEY_BLOCK = re.compile(
    rb"-----BEGIN ((?:[A-Z0-9]+ )*)PRIVATE KEY-----[ \t]*\n"
    rb"(?:[^\n]*\n)*?"
    rb"[A-Za-z0-9+/]{16,}={0,2}[ \t]*\n"
    rb"(?:[^\n]*\n)*?"
    rb"-----END \1PRIVATE KEY-----")

# Just the opening armour, for locating where the pre-encapsulation region ends.
PEM_BEGIN_ANY = re.compile(rb"-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY-----")

# Files bigger than this are not credibly a committed key and reading them all
# on every CI run is waste. A key that exceeds it would be missed, so the bound
# is generous rather than tight.
MAX_BYTES = 8 * 1024 * 1024


class Failure(Exception):
    """Usage / IO error -- exit 2, distinct from a gate failure."""


def tracked_files() -> list[str]:
    """Repo-relative paths of every tracked file.

    `git ls-files` and NOT a filesystem walk: untracked scratch keys are out of
    scope by design (they are not what a clone or a support bundle carries), and
    walking would additionally red on build/ and vcpkg trees.
    """
    out = subprocess.run(["git", "ls-files", "-z"], cwd=str(REPO_ROOT),
                         capture_output=True)
    if out.returncode != 0:
        raise Failure("git ls-files failed: "
                      + out.stderr.decode("utf-8", "replace").strip())
    return [p.decode("utf-8", "surrogateescape")
            for p in out.stdout.split(b"\0") if p]


def normalise(raw: bytes) -> bytes:
    """Fold CRLF -> LF. See the CRLF NOTE in the module docstring."""
    return raw.replace(b"\r\n", b"\n")


def contains_private_key(raw: bytes) -> bool:
    """True when @p raw holds a complete PEM private-key block."""
    return PEM_KEY_BLOCK.search(normalise(raw)) is not None


def marker_problem(rel: str, raw: bytes) -> str | None:
    """None when @p raw is properly labelled; otherwise the message to report."""
    data = normalise(raw)
    begin = PEM_BEGIN_ANY.search(data)
    if begin is None:                       # pragma: no cover - guarded by caller
        return None
    pos = data.find(MARKER_TOKEN)
    if pos < 0:
        return (
            f"{rel} contains an unlabelled PEM private key. Nothing IN THE FILE "
            f"says it is test material, so a secret scanner, a support bundle "
            f"or an engineer meeting it out of context cannot tell it from a "
            f"real leaked key -- and the cost of guessing wrong is asymmetric. "
            f"Add, AHEAD of the {begin.group(0).decode()} line (RFC 7468 §5.2 "
            f"requires PEM readers to skip text before the armour, so this is "
            f"inert):\n        "
            + MARKER_TEMPLATE.format(gen="<the script that generates it>")
              .replace("\n", "\n        ").rstrip()
            + "\n      If this is NOT test material it must not be committed at "
              "all: rotate the key and purge it from history.")
    if pos > begin.start():
        return (
            f"{rel} carries the '{MARKER_TOKEN.decode()}' marker but places it "
            f"AFTER the {begin.group(0).decode()} armour. Only text BEFORE the "
            f"armour is skipped by PEM readers (RFC 7468 §5.2); inside the "
            f"base64 body it corrupts the key. Move it to the top of the file.")
    return None


def check(problems: list, files=None, root: Path | None = None) -> list:
    """Append one message per problem; return the list.

    `files` / `root` exist so the self-tests can run the same code over a
    synthetic tree. Neither is passed in production.
    """
    root = REPO_ROOT if root is None else root
    files = tracked_files() if files is None else list(files)

    for rel in sorted(files):
        path = root / rel
        try:
            if not path.is_file() or path.stat().st_size > MAX_BYTES:
                continue
            raw = path.read_bytes()
        except OSError:
            continue
        if not contains_private_key(raw):
            continue
        msg = marker_problem(rel, raw)
        if msg:
            problems.append(msg)
    return problems


def scan(files=None, root: Path | None = None) -> list[str]:
    """Repo-relative paths of every tracked file holding a PEM private key."""
    root = REPO_ROOT if root is None else root
    files = tracked_files() if files is None else list(files)
    found = []
    for rel in sorted(files):
        path = root / rel
        try:
            if not path.is_file() or path.stat().st_size > MAX_BYTES:
                continue
            raw = path.read_bytes()
        except OSError:
            continue
        if contains_private_key(raw):
            found.append(rel)
    return found


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except (AttributeError, ValueError):  # pragma: no cover
            pass

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--list", action="store_true",
                    help="print every tracked file holding a PEM private key "
                         "and exit 0, without judging it")
    args = ap.parse_args(argv)

    try:
        keys = scan()
        if args.list:
            for k in keys:
                print(k)
            return 0
        problems = check([])
    except Failure as exc:
        print(f"[test-key-markers] ERROR: {exc}", file=sys.stderr)
        return 2

    if problems:
        print(f"[test-key-markers] FAIL — {len(problems)} problem(s):")
        for p in problems:
            print(f"  * {p}")
        return 1

    print(f"[test-key-markers] OK — {len(keys)} tracked file(s) hold a PEM "
          f"private key; every one carries the "
          f"'{MARKER_TOKEN.decode()}' marker ahead of its armour.")
    for k in keys:
        print(f"    {k}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
