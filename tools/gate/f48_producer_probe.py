# -*- coding: utf-8 -*-
"""End-to-end check that a REAL runner invocation emits nothing host-rooted.

WHY THIS EXISTS SEPARATELY FROM `run_ui_suite.py --self-test`. The self-test
exercises `portable_path`/`scrub_text` over synthetic inputs -- it proves the
rule is right. It cannot prove the rule is APPLIED at every point where a value
leaves the runner. Three of the four F48 emission points were found by asking
that second question, and two of them (a failure MESSAGE and pytest's own
per-file `.log`) are not fields whose names say "path".

So this drives the actual `run_one()` over an actual pytest subprocess whose
assertion embeds an absolute path, then inspects what was WRITTEN: the returned
record, the per-file log on disk, and the failure message extracted from the
JUnit XML. Measured on the unfixed producer, the same probe put 4 occurrences of
the account name and 7 absolute paths into the log alone.

Exit 0 with `[f48-probe] OK: N artifacts inspected, 0 host-rooted strings`, or
exit 1 naming every offender. Invoked by
`UiSuitePathHygiene.ARealRunnerInvocationEmitsNothingHostRooted`.
"""
from __future__ import annotations

import getpass
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tests.scripts.run_ui_suite import (  # noqa: E402
    _ABS_PATH_RE, collect_failures, merge_junits, run_one,
)

#: A test file that PASSES one case and FAILS another with an absolute path in
#: the assertion message. Both halves matter: the failure drives the message
#: and JUnit paths, and pytest's header quotes the rootdir either way.
_PROBE_SOURCE = '''# -*- coding: utf-8 -*-
"""Generated by tools/gate/f48_producer_probe.py. Not a product test."""
import pathlib


def test_passes():
    assert True


def test_fails_quoting_an_absolute_path():
    here = pathlib.Path(__file__).resolve()
    assert not here.exists(), f"probe failure quoting {here}"
'''


def _account_name() -> str:
    for getter in (lambda: os.environ.get("USERNAME", ""),
                   lambda: os.environ.get("USER", ""),
                   getpass.getuser):
        try:
            name = getter()
        except Exception:  # noqa: BLE001 - getpass raises on a headless rig
            name = ""
        if name and len(name) >= 3:
            return name
    return ""


def main() -> int:
    user = _account_name()

    def _pytest_explanation(log_path: pathlib.Path, account: str) -> str:
        """The tail of pytest's own output, redacted independently.

        GitHub #232: without this, an exit code arrives with no explanation and
        the retry heals the run, so there is nothing left to diagnose.

        Redaction is deliberately NOT the scrubber under test -- the account
        name and any absolute path are replaced here with a local pattern, so
        this diagnostic stays safe to print even in the case where the thing it
        is diagnosing is the scrubber itself.
        """
        try:
            if not log_path.exists():
                return ("\n    pytest wrote no log at all, so it likely died "
                        "before starting.")
            text = log_path.read_text(encoding="utf-8", errors="replace")
        except OSError as ex:
            return f"\n    (probe log unreadable: {ex})"

        if not text.strip():
            return "\n    pytest's log is empty."
        text = _ABS_PATH_RE.sub("<abs-path>", text)
        if account:
            text = text.replace(account, "<account>")
        tail = [ln for ln in text.strip().splitlines() if ln.strip()][-40:]
        return ("\n    pytest said (last %d line(s), redacted):\n" % len(tail)
                + "\n".join("      " + ln for ln in tail))
    work = Path(tempfile.mkdtemp(prefix="f48probe_"))
    offenders: list[str] = []
    inspected = 0
    try:
        (work / "per-file").mkdir(parents=True, exist_ok=True)
        target = work / "test_f48_probe.py"
        target.write_text(_PROBE_SOURCE, encoding="utf-8")
        junit = work / "per-file" / "probe.xml"
        log = work / "per-file" / "probe.log"

        # reap=False: this probe launches no application, and the gtest suite
        # it runs inside has 16 concurrent shards with live pdfe.exe children.
        # See the comment on run_one's `reap` parameter.
        record = run_one(target, junit, log, 300, REPO_ROOT, "unused.exe",
                         reap=False)

        def scan(label: str, text: str) -> None:
            nonlocal inspected
            inspected += 1
            for hit in _ABS_PATH_RE.findall(text):
                offenders.append(f"{label}: absolute path {hit!r}")
            if user and user in text:
                offenders.append(f"{label}: contains account name {user!r}")

        scan("run_one() record", json.dumps(record))
        if log.exists():
            scan("per-file log", log.read_text(encoding="utf-8",
                                               errors="replace"))
        else:
            offenders.append("per-file log was never written")

        # The RAW per-file JUnit XML, read as bytes off disk. This is the
        # artifact the first pass of the F48 fix missed: pytest writes it
        # directly, so nothing in the runner had ever touched its content, and
        # scrubbing collect_failures()'s derived `msg` cleaned only the copy.
        # Scanning the derived output alone is what let that pass unnoticed --
        # so both are scanned, and this one first.
        if junit.exists():
            scan("per-file junit xml", junit.read_text(encoding="utf-8",
                                                       errors="replace"))
        else:
            offenders.append("per-file junit xml was never written")

        # The MERGED XML, built from the per-file ones and uploaded by CI in
        # its own right. Merging is downstream of the scrub, so this should be
        # clean transitively -- asserted rather than assumed.
        merged = work / "ui-junit-merged.xml"
        merge_junits([junit], merged)
        if merged.exists():
            scan("merged junit xml", merged.read_text(encoding="utf-8",
                                                      errors="replace"))
        else:
            offenders.append("merged junit xml was never written")

        scan("collect_failures() output",
             json.dumps(collect_failures([junit], REPO_ROOT, work)))

        # Non-vacuity. A probe whose pytest never ran would inspect three empty
        # strings and pass, reporting protection that was never exercised.
        if record.get("returncode") != 1:
            # GitHub #232. This reported the CODE and discarded pytest's own
            # explanation of it, so an intermittent exit 2 (a collection or
            # usage error, meaning the probe never ran its one expected failing
            # case) could not be diagnosed after the fact -- and `run_gtest.py`
            # healed it on retry, leaving nothing behind at all.
            #
            # Attach the log. Note what is NOT done here: the log is scrubbed
            # with a LOCAL redaction rather than the scrubber this probe
            # exists to test. Using the code under test to sanitise its own
            # failure diagnostics would leak precisely when that code is
            # broken, which is the one moment this message matters.
            offenders.append(
                f"probe pytest returned {record.get('returncode')!r}, expected "
                f"1 (one failing case). The probe did not actually run, so "
                f"nothing was proved." + _pytest_explanation(log, user))
        failures = collect_failures([junit], REPO_ROOT, work)
        if len(failures) != 1:
            offenders.append(
                f"expected exactly 1 extracted failure, got {len(failures)}. "
                f"The path-bearing assertion message is the artifact this "
                f"probe exists to inspect.")
        elif "probe failure quoting" not in failures[0].get("msg", ""):
            offenders.append(
                "the extracted failure message is not the probe's own; the "
                "scrubber may have eaten more than the path.")
    finally:
        shutil.rmtree(work, ignore_errors=True)

    if offenders:
        print("[f48-probe] FAILED — a real runner invocation emitted "
              "host-rooted data:", file=sys.stderr)
        for o in offenders:
            print("  - " + o, file=sys.stderr)
        return 1
    print(f"[f48-probe] OK: {inspected} artifacts inspected, "
          f"0 host-rooted strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
