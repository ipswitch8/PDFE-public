#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Pins scripts/security/gen_sbom.py's reproducibility (GitHub #71, phase-6).

Two properties are asserted, neither of which a "does it exit 0" check would
catch:

1. **Determinism**: given the same manifest, the same vcpkg status db, the
   same Cargo.lock and the same ``--created`` stamp, two independent
   invocations produce byte-identical SBOM files. A generator that pulled in
   wall-clock time, dict iteration order, or filesystem enumeration order
   anywhere would fail this on a re-run without needing a second machine.
2. **Content correctness against a real regression shape**: the generated
   SBOM contains the exact (name, version, purl, SPDXID) triple for every
   package in a synthetic-but-representative manifest/status/lock fixture,
   with the transitive closure correctly walked through a feature stanza,
   and versions correctly stripped of the vcpkg ``Port-Version`` suffix to
   match the currently-committed artifact's schema (see gen_sbom.py's module
   docstring for why). A generator that dropped a package, mis-versioned it,
   or fell back to ``NOASSERTION`` would fail this without needing to touch
   the real (network- and vcpkg-dependent) install tree -- this test is
   fully offline, as required for the fast-checks lane.

3. **SPDXID uniqueness and charset conformance** (GitHub #181): no two packages
   in a generated document -- nor in the committed artifact -- share an element
   id, every id is inside SPDX 2.3's ``SPDXRef-[A-Za-z0-9.-]+`` charset, and a
   collision the charset sanitiser would otherwise create makes the generator
   FAIL rather than emit. The PowerShell second implementation
   (``scripts/security/run_deps.ps1``) is checked for the same scheme, because
   it writes the same artifact on a real audit run.

Everything except the committed-artifact check runs against fixtures built in
tmp_path; that one check reads the committed SBOM as a plain file. Nothing here
needs a built tree or the network.

Run:
    python -m pytest tools/gate/test_gen_sbom_reproducibility.py -q
"""
from __future__ import annotations

import io
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "security"))
import gen_sbom  # noqa: E402


VCPKG_JSON = """{
  "name": "fixture",
  "version-string": "0.0.0",
  "dependencies": [
    {"name": "qtbase", "features": ["widgets"]},
    "libmupdf",
    {"name": "curl", "platform": "!windows"}
  ]
}
"""

# qtbase has a feature stanza (Feature: widgets) whose Depends line pulls in
# "harfbuzz" -- a dependency the closure walk must not miss by stopping at
# the base stanza. libmupdf carries a Port-Version, which must be dropped
# from versionInfo per gen_sbom's documented schema match. curl is declared
# platform-conditional but still resolvable here (mirrors the real repo,
# where sbom_direct_deps.direct_dependencies() includes it unconditionally).
VCPKG_STATUS = """Package: qtbase
Version: 6.10.0
Port-Version: 1
Depends: zlib
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed

Package: qtbase
Feature: widgets
Depends: harfbuzz
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed

Package: harfbuzz
Version: 11.0.0
Depends: freetype
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed

Package: freetype
Version: 2.13.3
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed

Package: zlib
Version: 1.3.1
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed

Package: libmupdf
Version: 1.26.10
Port-Version: 3
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed

Package: curl
Version: 8.18.0
Port-Version: 1
Architecture: x64-windows
Multi-Arch: same
Status: install ok installed
"""

CARGO_LOCK = """# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "foldhash"
version = "0.1.5"

[[package]]
name = "foldhash"
version = "0.2.0"

[[package]]
name = "cfg-if"
version = "1.0.0"
"""

CREATED = "2026-09-11T00:00:00Z"

# Every triple gen_sbom.py MUST emit from the fixture above. This is the
# regression shape a mutant (dropped package / wrong version / NOASSERTION)
# has to survive to slip past the test -- see the mutation-verification note
# in the pipeline report for the mutant actually run against this.
#
# SPDXID scheme UPDATED for GitHub #181: ``SPDXRef-<ecosystem>-<name>-<version>``,
# replacing the name-only ``SPDXRef-<name>``. The two foldhash rows below are the
# whole point -- under the old scheme both were ``SPDXRef-foldhash``, and the
# fixture asserted that collision as expected behaviour. ``cfg-if`` also changes
# shape: ``-`` is legal in an SPDX id, so it is no longer mangled to ``cfg_if``
# (which was off-charset in the first place).
EXPECTED_TRIPLES = {
    ("qtbase", "6.10.0", "pkg:vcpkg/qtbase@6.10.0", "SPDXRef-vcpkg-qtbase-6.10.0"),
    ("harfbuzz", "11.0.0", "pkg:vcpkg/harfbuzz@11.0.0", "SPDXRef-vcpkg-harfbuzz-11.0.0"),
    ("freetype", "2.13.3", "pkg:vcpkg/freetype@2.13.3", "SPDXRef-vcpkg-freetype-2.13.3"),
    ("zlib", "1.3.1", "pkg:vcpkg/zlib@1.3.1", "SPDXRef-vcpkg-zlib-1.3.1"),
    ("libmupdf", "1.26.10", "pkg:vcpkg/libmupdf@1.26.10", "SPDXRef-vcpkg-libmupdf-1.26.10"),
    ("curl", "8.18.0", "pkg:vcpkg/curl@8.18.0", "SPDXRef-vcpkg-curl-8.18.0"),
    ("foldhash", "0.1.5", "pkg:cargo/foldhash@0.1.5", "SPDXRef-cargo-foldhash-0.1.5"),
    ("foldhash", "0.2.0", "pkg:cargo/foldhash@0.2.0", "SPDXRef-cargo-foldhash-0.2.0"),
    ("cfg-if", "1.0.0", "pkg:cargo/cfg-if@1.0.0", "SPDXRef-cargo-cfg-if-1.0.0"),
}

# SPDX 2.3, clause 6.3: an element id is "SPDXRef-" followed by letters, digits,
# "." and "-". Nothing else -- notably NOT "_", which the pre-#181 scheme emitted.
SPDX_ID_RE = re.compile(r"^SPDXRef-[A-Za-z0-9.\-]+$")

COMMITTED_SBOM = (
    Path(__file__).resolve().parents[2]
    / "tests" / "security" / "reports" / "deps" / "sbom.spdx.json"
)


def _write_fixtures(tmp_path: Path):
    vcpkg_json = tmp_path / "vcpkg.json"
    vcpkg_json.write_text(VCPKG_JSON, encoding="utf-8")

    status_dir = tmp_path / "vcpkg_installed" / "vcpkg"
    status_dir.mkdir(parents=True)
    status_path = status_dir / "status"
    status_path.write_text(VCPKG_STATUS, encoding="utf-8")

    cargo_lock = tmp_path / "Cargo.lock"
    cargo_lock.write_text(CARGO_LOCK, encoding="utf-8")

    return vcpkg_json, status_path, cargo_lock


def test_two_runs_with_fixed_created_are_byte_identical(tmp_path):
    vcpkg_json, status_path, cargo_lock = _write_fixtures(tmp_path)

    out_a = tmp_path / "run_a.spdx.json"
    out_b = tmp_path / "run_b.spdx.json"

    rc_a = gen_sbom.main([
        "--vcpkg-json", str(vcpkg_json),
        "--vcpkg-status", str(status_path),
        "--cargo-lock", str(cargo_lock),
        "--created", CREATED,
        "--output", str(out_a),
    ])
    rc_b = gen_sbom.main([
        "--vcpkg-json", str(vcpkg_json),
        "--vcpkg-status", str(status_path),
        "--cargo-lock", str(cargo_lock),
        "--created", CREATED,
        "--output", str(out_b),
    ])

    assert rc_a == 0
    assert rc_b == 0
    bytes_a = out_a.read_bytes()
    bytes_b = out_b.read_bytes()
    assert bytes_a == bytes_b, "same inputs + same --created must yield byte-identical output"


def test_generated_content_matches_expected_closure_and_versions(tmp_path):
    """Not a vacuous existence check: asserts the exact package triples.

    Covers three properties in one fixture: the transitive closure crosses a
    feature-stanza boundary (harfbuzz, pulled in only via qtbase's `widgets`
    Feature stanza), Port-Version is stripped from versionInfo (libmupdf,
    curl, qtbase all carry one in the fixture), and cargo duplicate names at
    different versions are both preserved (foldhash 0.1.5 and 0.2.0).
    """
    vcpkg_json, status_path, cargo_lock = _write_fixtures(tmp_path)
    doc = gen_sbom.build_sbom(vcpkg_json, status_path, cargo_lock, CREATED)

    actual_triples = set()
    for pkg in doc["packages"]:
        purl = pkg["externalRefs"][0]["referenceLocator"]
        actual_triples.add((pkg["name"], pkg["versionInfo"], purl, pkg["SPDXID"]))

    missing = EXPECTED_TRIPLES - actual_triples
    unexpected = actual_triples - EXPECTED_TRIPLES
    assert not missing, "gen_sbom.py dropped or mis-emitted: {0}".format(missing)
    assert not unexpected, "gen_sbom.py emitted unexpected packages: {0}".format(unexpected)
    assert len(doc["packages"]) == len(EXPECTED_TRIPLES)


def test_missing_declared_dependency_version_fails_closed(tmp_path):
    """A direct dependency the status db cannot resolve must ERROR, not emit
    a silently-incomplete SBOM (meta-audit SEC-76/SEC-77 -- the same failure
    mode this schema already survived once for qtsvg/tesseract/pugixml/curl).
    """
    vcpkg_json = tmp_path / "vcpkg.json"
    vcpkg_json.write_text(
        '{"name": "fixture", "version-string": "0.0.0", '
        '"dependencies": ["nonexistent-port"]}',
        encoding="utf-8",
    )
    status_dir = tmp_path / "vcpkg_installed" / "vcpkg"
    status_dir.mkdir(parents=True)
    status_path = status_dir / "status"
    status_path.write_text("Package: zlib\nVersion: 1.3.1\n", encoding="utf-8")
    cargo_lock = tmp_path / "Cargo.lock"
    cargo_lock.write_text("version = 3\n", encoding="utf-8")

    try:
        gen_sbom.build_sbom(vcpkg_json, status_path, cargo_lock, CREATED)
        assert False, "expected SbomGenerationError for an unresolvable direct dependency"
    except gen_sbom.SbomGenerationError as exc:
        assert "nonexistent-port" in str(exc)


def test_structural_diff_ignores_created_and_namespace_but_not_packages():
    a = {
        "documentNamespace": "https://example.invalid/sbom-1",
        "creationInfo": {"created": "2026-01-01T00:00:00Z", "creators": ["Tool: x"]},
        "packages": [
            {"name": "zlib", "versionInfo": "1.3.1", "SPDXID": "SPDXRef-zlib",
             "externalRefs": [{"referenceType": "purl", "referenceLocator": "pkg:vcpkg/zlib@1.3.1"}]},
        ],
    }
    b = {
        "documentNamespace": "https://example.invalid/sbom-2",
        "creationInfo": {"created": "2026-02-02T00:00:00Z", "creators": ["Tool: y"]},
        "packages": [
            {"name": "zlib", "versionInfo": "1.3.1", "SPDXID": "SPDXRef-zlib",
             "externalRefs": [{"referenceType": "purl", "referenceLocator": "pkg:vcpkg/zlib@1.3.1"}]},
        ],
    }
    diff = gen_sbom.structural_diff(a, b)
    assert diff["equivalent"], diff

    c = dict(b)
    c["packages"] = [
        {"name": "zlib", "versionInfo": "1.3.2", "SPDXID": "SPDXRef-zlib",
         "externalRefs": [{"referenceType": "purl", "referenceLocator": "pkg:vcpkg/zlib@1.3.2"}]},
    ]
    diff2 = gen_sbom.structural_diff(a, c)
    assert not diff2["equivalent"]
    assert diff2["only_in_a"] and diff2["only_in_b"]


# ── GitHub #181: SPDXID uniqueness ──────────────────────────────────────────
#
# The defect arrived by copy-paste of a name-only id expression (twice: once in
# gen_sbom.py, once in run_deps.ps1) and shipped in the committed artifact as
# 211 packages under 203 ids. These four tests close the three ways it can come
# back: the generator emitting a colliding id, the committed artifact carrying
# one, and the charset sanitiser quietly mapping two distinct packages onto one
# id. Mutation-verified by reverting spdx_id_for() to name-only -- see the
# pipeline report for the observed failure text.


def _duplicate_ids(packages):
    counts = {}
    for pkg in packages:
        counts.setdefault(pkg["SPDXID"], []).append(
            "{0}@{1}".format(pkg["name"], pkg["versionInfo"])
        )
    return {key: value for key, value in counts.items() if len(value) > 1}


def test_generated_spdx_ids_are_unique_and_charset_conformant(tmp_path):
    """No two packages share an id, and every id is SPDX-legal.

    The fixture carries foldhash at 0.1.5 AND 0.2.0 -- one component at two
    versions is precisely the shape that collided under the name-only scheme,
    so this is not a vacuous "all distinct because everything is distinct".
    """
    vcpkg_json, status_path, cargo_lock = _write_fixtures(tmp_path)
    doc = gen_sbom.build_sbom(vcpkg_json, status_path, cargo_lock, CREATED)

    packages = doc["packages"]
    foldhash_ids = {p["SPDXID"] for p in packages if p["name"] == "foldhash"}
    assert len(foldhash_ids) == 2, (
        "the fixture must contain two foldhash versions for this test to mean "
        "anything; got {0}".format(sorted(foldhash_ids))
    )

    duplicates = _duplicate_ids(packages)
    assert not duplicates, "duplicate SPDXIDs: {0}".format(duplicates)
    assert len({p["SPDXID"] for p in packages}) == len(packages)

    offenders = [p["SPDXID"] for p in packages if not SPDX_ID_RE.match(p["SPDXID"])]
    assert not offenders, "SPDXIDs outside the SPDX 2.3 charset: {0}".format(offenders)


def test_committed_sbom_has_no_duplicate_spdx_ids():
    """The REGENERATED artifact itself, not just the generator (GitHub #181).

    A generator fix nobody re-ran would leave the shipped document colliding,
    and it is the document a CVE triage reads. Pure file read: offline, no
    build tree, no network.
    """
    assert COMMITTED_SBOM.exists(), "{0} is missing".format(COMMITTED_SBOM)
    with io.open(COMMITTED_SBOM, "r", encoding="utf-8") as handle:
        doc = json.load(handle)

    packages = doc["packages"]
    assert packages, "the committed SBOM enumerates no packages at all"

    duplicates = _duplicate_ids(packages)
    assert not duplicates, (
        "{0} colliding SPDXID(s) in {1}: {2}. SPDX 2.3 requires element ids to "
        "be unique; regenerate with scripts/security/gen_sbom.py (never hand-edit)"
        .format(len(duplicates), COMMITTED_SBOM.name, duplicates)
    )
    assert len({p["SPDXID"] for p in packages}) == len(packages)

    offenders = [p["SPDXID"] for p in packages if not SPDX_ID_RE.match(p["SPDXID"])]
    assert not offenders, "SPDXIDs outside the SPDX 2.3 charset: {0}".format(offenders)


def test_sanitiser_collision_fails_closed_rather_than_emitting_a_duplicate(tmp_path):
    """The charset sanitiser is not injective, so it is not trusted.

    ``a_b`` and ``a-b`` both reduce to ``a-b``. Two crates whose names differ
    only there, at the same version, would collide again -- so build_sbom must
    REFUSE, not emit. (Also pins the near-miss: version ``1_0`` and version
    ``1.0`` must NOT be conflated, which is the classic way a "fix" reintroduces
    the bug it removed.)
    """
    vcpkg_json = tmp_path / "vcpkg.json"
    vcpkg_json.write_text(
        '{"name": "fixture", "version-string": "0.0.0", "dependencies": ["zlib"]}',
        encoding="utf-8",
    )
    status_dir = tmp_path / "vcpkg_installed" / "vcpkg"
    status_dir.mkdir(parents=True)
    status_path = status_dir / "status"
    status_path.write_text("Package: zlib\nVersion: 1.3.1\n", encoding="utf-8")

    # Near-miss first: 1_0 -> "1-0", 1.0 -> "1.0". Distinct, so no error.
    near_miss = tmp_path / "near_miss.lock"
    near_miss.write_text(
        '[[package]]\nname = "widget"\nversion = "1_0"\n\n'
        '[[package]]\nname = "widget"\nversion = "1.0"\n',
        encoding="utf-8",
    )
    doc = gen_sbom.build_sbom(vcpkg_json, status_path, near_miss, CREATED)
    widget_ids = sorted(p["SPDXID"] for p in doc["packages"] if p["name"] == "widget")
    assert widget_ids == ["SPDXRef-cargo-widget-1-0", "SPDXRef-cargo-widget-1.0"], widget_ids

    # Real collision: two names that sanitise to the same segment, same version.
    colliding = tmp_path / "colliding.lock"
    colliding.write_text(
        '[[package]]\nname = "a_b"\nversion = "1.0.0"\n\n'
        '[[package]]\nname = "a-b"\nversion = "1.0.0"\n',
        encoding="utf-8",
    )
    try:
        gen_sbom.build_sbom(vcpkg_json, status_path, colliding, CREATED)
        assert False, "expected SbomGenerationError for a sanitiser-induced collision"
    except gen_sbom.SbomGenerationError as exc:
        message = str(exc)
        assert "SPDXRef-cargo-a-b-1.0.0" in message, message
        assert "a_b@1.0.0" in message and "a-b@1.0.0" in message, message


def test_powershell_generator_uses_the_same_disambiguated_id_scheme():
    """run_deps.ps1 is the SECOND implementation -- and how #181 arrived.

    ``scripts/security/run_deps.ps1`` writes the same artifact during a real
    dependency-audit run. If it kept the name-only id expression, the very next
    run would overwrite the regenerated SBOM with a colliding one and this
    suite's other checks would only notice after the fact. Assert its id
    expression is built from ecosystem AND name AND version, and that the
    name-only form is gone.
    """
    ps1 = Path(__file__).resolve().parents[2] / "scripts" / "security" / "run_deps.ps1"
    text = ps1.read_text(encoding="utf-8")

    assert "'SPDXRef-' + ($p.name -replace" not in text, (
        "run_deps.ps1 still derives the SPDXID from the package name alone "
        "(GitHub #181); keep it in lockstep with gen_sbom.spdx_id_for()"
    )
    for segment in ("_spdx_component $p.ecosystem",
                    "_spdx_component $p.name",
                    "_spdx_component $p.version"):
        assert segment in text, "run_deps.ps1 no longer composes its SPDXID from " + segment
    assert "SPDXID COLLISION" in text, (
        "run_deps.ps1 must still fail closed on a duplicate id rather than writing it"
    )
