// ─────────────────────────────────────────────────────────────────────────────
// AC(g) — per-line font size on the two-line italic-serif fixture is consistent
// with the actual line heights (the heading line is far larger than the body
// line), and (algorithmically) per-line sizing in an italic region tracks
// per-line heights rather than broadcasting a single region average.
// ─────────────────────────────────────────────────────────────────────────────
TEST_F(TextEditFontIdentityTest, Fixture_TwoLineItalicSerif_PerLineSizesConsistentWithHeights) {
    if (!doc_) GTEST_SKIP() << kFixture << " not available";
    auto page = doc_->page(0);
    ASSERT_NE(page, nullptr);

    struct LineMeasure { float avgSize; double height; };
    std::vector<LineMeasure> lines;
    for (const auto& block : page->extractText()) {
        for (const auto& line : block.lines) {
            if (line.chars.empty()) continue;
            float sum = 0.0f; int n = 0;
            for (const auto& ch : line.chars) {
                if (ch.fontSize > 0.0f) { sum += ch.fontSize; ++n; }
            }
            if (n == 0) continue;
            lines.push_back({sum / n, line.boundingBox.height()});
        }
    }
    ASSERT_GE(lines.size(), 2u) << "fixture must yield two text lines";

    auto big = std::max_element(lines.begin(), lines.end(),
        [](const LineMeasure& a, const LineMeasure& b) { return a.avgSize < b.avgSize; });
    auto small = std::min_element(lines.begin(), lines.end(),
        [](const LineMeasure& a, const LineMeasure& b) { return a.avgSize < b.avgSize; });

    // Heading 33pt vs body 13pt => ~2.5x. The per-line sizes must differ
    // markedly (not a broadcast single value) and the larger font must also be
    // the taller line — i.e. per-line size tracks line height.
    EXPECT_GT(big->avgSize, small->avgSize + 5.0f)
        << "the two lines' per-line sizes barely differ (" << small->avgSize
        << " vs " << big->avgSize << ") — looks like a broadcast region average";
    EXPECT_GT(big->avgSize / small->avgSize, 1.8f)
        << "heading/body size ratio " << (big->avgSize / small->avgSize)
        << " below expected ~2.5x";
    EXPECT_GE(big->height, small->height)
        << "the larger-font line must be the taller line (size tracks height)";
    // Sanity: the measured sizes are near the authored 33pt / 13pt.
    EXPECT_NEAR(big->avgSize, 33.0f, 4.0f);
    EXPECT_NEAR(small->avgSize, 13.0f, 4.0f);
}

TEST(TextEditFontIdentityPerLine, DetectProperties_ItalicRegion_PerLineSizesTrackHeights) {
    pdfe::core::MuPdfContext context;
    pdfe::fonts::FontAnalysisCache cache;
    pdfe::fonts::EmbeddedFontAnalyzer analyzer(&context);
    pdfe::fonts::SubstituteFontSelector selector(&analyzer, &cache);
    pdfe::tre::FontMatcher matcher(&selector, &analyzer);

    // Two italic lines (baselineSlope 0.15 => isItalic) at x_size 12 and 30 px
    // @300 DPI => 2.88pt and 7.2pt. baselineOffset 0 isolates the x_size term.
    auto region = makeLinesRegion({12.0f, 30.0f}, 3.0f, 12.0f, /*slope=*/0.15f);
    QImage blank(200, 400, QImage::Format_ARGB32);
    blank.fill(Qt::white);

    auto props = matcher.detectProperties(region, blank, 300);
    EXPECT_TRUE(props.isItalic) << "baselineSlope 0.15 region should read italic";
    ASSERT_EQ(props.perLineFontSizePt.size(), 2u);
    EXPECT_NEAR(props.perLineFontSizePt[0], 2.88f, 0.2f);
    EXPECT_NEAR(props.perLineFontSizePt[1], 7.2f, 0.2f);
    EXPECT_GT(props.perLineFontSizePt[1], props.perLineFontSizePt[0] + 1.0f)
        << "per-line sizes must track each line's own height, not a broadcast "
           "region average";
}
