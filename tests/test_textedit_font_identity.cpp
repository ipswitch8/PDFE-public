// ─────────────────────────────────────────────────────────────────────────────
// Untruncated /BaseFont recovery. MuPDF stores a font's name in a char[32]
// buffer, so fz_font_name() clips any /BaseFont longer than 31 chars — dropping
// a trailing style keyword and silently losing italic in the edit overlay.
// TextExtractor now recovers the full /BaseFont from the PDF font dict
// (FontNameUtil). Proof fixture embedded_longname_italic_serif.pdf has a 36-char
// BaseFont "XXXXXX+Palatino Linotype Bold Italic"; its 31-char truncation
// ("XXXXXX+Palatino Linotype Bold I") hides "Italic", so a passing assertion
// here can only come from the untruncation path.
TEST(TextEditUntruncatedBaseFont, LongNameSpan_FontNameUntruncated_OverlayItalic) {
    auto ctx = std::make_shared<MuPdfContext>();
    auto p = std::filesystem::path(fixturesDir()) /
             "embedded_longname_italic_serif.pdf";
    if (!std::filesystem::exists(p))
        GTEST_SKIP() << "embedded_longname_italic_serif.pdf not available";
    auto doc = Document::open(ctx, p);
    ASSERT_TRUE(doc) << "failed to open long-name fixture";
    auto page = doc->page(0);
    ASSERT_TRUE(page);

    std::string fontName;
    for (const auto& block : page->extractText()) {
        for (const auto& line : block.lines) {
            for (const auto& ch : line.chars) {
                if (!ch.fontName.empty()) { fontName = ch.fontName; break; }
            }
            if (!fontName.empty()) break;
        }
        if (!fontName.empty()) break;
    }
    ASSERT_FALSE(fontName.empty()) << "no extractable span in long-name fixture";

    // The recovered name must exceed MuPDF's 31-char cap and still carry "Italic"
    // (the keyword sits past char 31, so a truncated name could not contain it).
    EXPECT_GT(fontName.size(), static_cast<std::size_t>(31))
        << "fontName still truncated at MuPDF's char[32] cap: '" << fontName << "'";
    EXPECT_NE(fontName.find("Italic"), std::string::npos)
        << "untruncated /BaseFont must retain the trailing 'Italic'; got '"
        << fontName << "'";

    // The overlay name-parses that string, so it now sets italic.
    QFont font = TextEditTool::buildOverlayFont(makeSpan(fontName, 33.0f), 1.0f);
    EXPECT_TRUE(font.italic())
        << "overlay must be italic once the untruncated /BaseFont is supplied; "
        << "fontName='" << fontName << "'";
}

