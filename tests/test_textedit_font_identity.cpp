    ASSERT_FALSE(baseFont.empty());
    auto page = doc_->page(0);
    ASSERT_NE(page, nullptr);

    // The embedded face is bold (macStyle bold bit, usWeightClass 700) — the
    // BaseFont name '*-BoldItalic' carries that. The resolver picks the bold
