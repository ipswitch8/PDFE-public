def _click_canvas_pdf_point(win, pdf_x: float, pdf_y: float):
    """Dispatch a click at a PDF-space point on the active canvas.

    Pipeline f7c2a4e8 phase-2 (A4 / P-GAP-97): switched to the
    testClickByPdfCoordPipe Q_INVOKABLE seam (PdfCanvas::clickByPdfCoord)
    instead of pyautogui screen-coordinate calculation. The pyautogui
    approach used a fit-page assumption that doesn't hold when the
    canvas zoom/pan differs from the test's mental model; this caused
    the test_follow_named_nextpage_link_advances_one_page test to
    fail in the b5e3a9f2 final sweep because the click missed the
    link's hit-zone.

    The pipe synthesizes Qt mouse press + release events directly
    through PdfCanvas::clickByPdfCoord — the same code path a real
    click takes — but with exact PDF coords, bypassing the
    screen-coord conversion.

    PDF /Rect coords in the fixture are Y-up (origin bottom-left);
    PdfCanvas::clickByPdfCoord uses MuPDF/fitz coords (top-left Y-down).
    The conversion is: fitz_y = page_height - pdf_y. The fixture page
    is US Letter (792pt tall). pageIndex 0 is assumed.
    """
    from tests.ui_automation.harness.dialog_helpers import find_by_suffix
    pipe = find_by_suffix(win, "testClickByPdfCoordPipe")
    if pipe is None:
        # WIN-45 / F25: unreachable -> recorded 'blocked', then FAIL.
        _reach = (
            "testClickByPdfCoordPipe not reachable; PDFE_TEST_PIPES must be set"
        )
        record_matrix_result(current_test_id(), "blocked", _reach)
        pytest.fail(
            f"WIN-45 reachability blocked (recorded non-pass, not skipped): {_reach}")
    # Convert Y-up PDF coord to fitz Y-down for the pipe.
    fitz_y = 792.0 - pdf_y
    try:
        pipe.set_edit_text(f"0,{pdf_x},{fitz_y}")
    except Exception as e:  # noqa: BLE001
        # GitHub #209 follow-up, MEASURED 2026-09-18. This used to be
        # ``pytest.skip("pipe write failed")`` — a skip is green, and the
        # premise is false. The write DOES land; what fails is the UIA reply.
        #
        #   _ctypes.COMError: (-2146233083, None, (None, None, None, 0, None))
        #   at pywinauto/controls/uia_controls.py:462 iface_value.SetValue()
        #
        # PdfCanvas's textChanged handler runs the click SYNCHRONOUSLY, and
        # for the /Launch link that handler opens a modal
        # ``QMessageBox::warning(this, tr("Launch external file?"), ...)``
        # (src/ui/MainWindow.cpp:7427-7433). The modal event loop starts
        # before ValuePattern::SetValue can return, so the RPC never gets its
        # reply. The click happened; only the acknowledgement was lost. The
        # only case that hits this is the one whose whole purpose is to prove
        # that modal appears — and it was skipping instead of asserting it.
        #
        # So: report the condition to the caller rather than deciding for it.
        # A COMError means "delivered, reply blocked — go look for the modal".
        if type(e).__name__ == "COMError":
            return False
        # Anything else is a genuine seam failure: recorded non-pass, then
        # FAIL. WIN-45 / F25 — never a skip.
        _reach = f"testClickByPdfCoordPipe write failed: {type(e).__name__}: {e}"
        record_matrix_result(current_test_id(), "blocked", _reach)
        pytest.fail(
            f"WIN-45 reachability blocked (recorded non-pass, not skipped): {_reach}")
    time.sleep(0.2)
    return True


def _read_page_status(win):
    """Read the current page indicator from the status-bar pageLabel
    (objectName 'pageLabel' inside the QStatusBar). UIA exposes the
    QLabel's accessibleName ("Page Number") as Name and the displayed
    text ("Page X of Y") as Description (mirrored by StatusBar::
    setPageInfo per Pipeline F phase-3)."""
    for aid in ("QApplication.mainWindow.statusBar.pageLabel",
                "QApplication.mainWindow.pageInfoLabel",
                "pageLabel",
                "pageInfoLabel"):
        try:
            status = win.child_window(auto_id=aid)
            status.wait("visible", timeout=3)
            # Try Description (UIA help_text) first — that's where
            # the displayed text lives. Fall back to window_text for
            # widgets that haven't been migrated yet.
            try:
                desc = status.element_info.element.CurrentHelpText
                if desc:
                    return desc
            except Exception:
                pass
            return status.window_text()
        except Exception:
            continue
    return None


