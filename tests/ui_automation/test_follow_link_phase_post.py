# GitHub #135 — RESOLVED 2026-09-08 (pipeline backlog-workable-p82 phase-17).
#
# The recorded symptom was "lands on Page 3 of 3 instead of Page 2 of 3", with
# two candidate causes: the click resolving to the nearby GoTo-to-page-3 link,
# or the Named handler advancing by two. MEASURED, it was neither. By the time
# this was investigated the observable had changed to "the click does nothing
# at all" (status stayed "Page 1 of 3"), live and in-process alike.
