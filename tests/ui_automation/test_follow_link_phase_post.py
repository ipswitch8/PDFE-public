# `linkFollowRequested` callback consulted before the Select tool's press
# (creation tools deliberately keep their own clicks).
#
# The marker is REMOVED rather than switched to strict=True: strict=False
# swallowed an unexpected pass, so this test could never have announced the
# fix. See tests/test_follow_link.cpp::FollowLinkFixtureTest for the
# GoogleTest oracles that pin the behaviour without a live desktop.
