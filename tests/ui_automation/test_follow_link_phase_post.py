#: The exact title of the confirmation modal, src/ui/MainWindow.cpp:7428.
#: A literal rather than a ``.*Launch.*`` regex: the loose pattern also
#: matches the main window once a document called anything with "Launch" in
#: it is open, and it matched nothing useful here anyway because the modal is
#: not in the UIA tree at all.
LAUNCH_CONFIRM_TITLE = "Launch external file?"


def test_follow_launch_link_prompts_confirmation(pdfe_app):
    """follow_launch_link_prompts — clicking the /Launch link must raise a
    confirmation modal BEFORE any shell invocation; Cancel dismisses it.

    Two things were wrong here and both made the case green without testing
    anything (GitHub #209 follow-up, measured 2026-09-18):

      1. ``_click_canvas_pdf_point`` skipped on "pipe write failed". The write
        did not fail — the modal this test exists to prove blocked the UIA
        reply. See the comment there.
      2. The detection was ``win.child_window(title_re=".*Launch.*").wait(
        "visible")`` — UIA, on a Qt app-modal ``QMessageBox``. CLAUDE.md says
        that cannot work and never has; the ``except: pytest.skip("Launch
        confirmation dialog not captured")`` underneath it made the
        impossibility look like an absent precondition.

    Now uses ``tests/helpers/modal_dialog`` (raw Win32 ``EnumWindows``), the
    documented answer. Oracle: a visible top-level window of this process
    titled exactly "Launch external file?" (MainWindow.cpp:7428) must appear.
    Delete the prompt and let /Launch dispatch straight to the shell — the
    security defect this case guards — and no such window exists, so it fails.
    """
    import sys as _sys
    from pathlib import Path as _Path
    _root = str(_Path(__file__).resolve().parents[2])
    if _root not in _sys.path:
        _sys.path.insert(0, _root)
    from tests.helpers.modal_dialog import (
        wait_for_window, close_window, list_process_windows,
    )

    app, win = pdfe_app
    pid = app.process

    # Baseline: the modal must not already be up, or "it appeared" would be
    # measuring the starting state rather than the click.
    before = [t for _, t in list_process_windows(pid)]
    assert not any(LAUNCH_CONFIRM_TITLE in t for t in before), (
        f"the confirmation window is already open before the click: {before!r}"
    )

    _click_canvas_pdf_point(win, 250, 617)

    hwnd = wait_for_window(pid, LAUNCH_CONFIRM_TITLE, timeout=15.0, poll=0.25)
    if hwnd is None:
        record_matrix_result(
            "follow_launch_link_prompts", "red",
            f"no window titled {LAUNCH_CONFIRM_TITLE!r} after clicking the "
            f"/Launch link; windows seen: "
            f"{[t for _, t in list_process_windows(pid)]!r}",
        )
        pytest.fail(
            f"/Launch link did not prompt: no {LAUNCH_CONFIRM_TITLE!r} window "
            f"(src/ui/MainWindow.cpp:7428). A /Launch action that dispatches "
            f"without confirmation is a security defect, not a skip."
        )

    # Cancel is the QMessageBox escape button (MainWindow.cpp:7433), so
    # WM_CLOSE is a decline — nothing is launched.
    close_window(hwnd)
    time.sleep(1.0)
    still_open = [t for _, t in list_process_windows(pid)]
    from tests.ui_automation.conftest import assert_recorded
    assert_recorded(
        "follow_launch_link_prompts",
        not any(LAUNCH_CONFIRM_TITLE in t for t in still_open),
        f"the confirmation modal did not close on WM_CLOSE: {still_open!r}",
        green_notes=(
            "GitHub #209 follow-up: /Launch link raises the "
            f"{LAUNCH_CONFIRM_TITLE!r} modal (detected via Win32 EnumWindows, "
            "not UIA) and Cancel dismisses it without dispatch"
        ),
    )


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-v"]))
