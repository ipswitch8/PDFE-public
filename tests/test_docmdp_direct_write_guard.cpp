// -*- coding: utf-8 -*-
//
// Meta-audit 2026-07 follow-up, phase F24 REMEDIATION — security-audit gate,
// finding 1: the DocMDP save guard was BYPASSABLE, so it was decorative for
// four write paths.
//
// The gate found it, which is the process working. F24 wired DocMdpSaveGuard
// into pdfe::core::Document::save/saveAs/saveIncremental and stopped there.
// Four content-editing engines never touch pdfe::core::Document at all — they
// pdf_open_document() the input, mutate it, and pdf_save_document() the result
// themselves:
//
//   src/batch/BatchEngine.cpp                (watermark)
//   src/headerfooter/HeaderFooterEngine.cpp  (apply + remove)
//   src/optimize/OptimizeEngine.cpp          (rewrite / sanitize / linearize)
//   src/reflow/AlignmentInjector.cpp         (apply + remove)
//
// `grep -ci 'docmdp|enforcer|certif|saveguard'` returned 0 in all four. A
// watermark aimed at a /P 1 certified document overwrote it in place with no
// refusal and no warning — through the same product, on the same file, that
// Document::save() would have refused. So the phase's acceptance criterion ("a
// production caller consults DocMdpEnforcer before a certified document is
// mutated or saved") was only partly true.
//
// The fix is src/signatures/DocMdpDirectWriteGuard.cpp, which applies the SAME
// product decision to these engines (refuse in place, warn and proceed when
// writing elsewhere) using the SAME decode (readDocMdpLevel) and the SAME
// permission matrix (DocMdpEnforcer::changePermittedAt). A divergent second
// policy would have been a worse outcome than the gap.
//
// EVERY ENFORCEMENT HERE HAS A DISCRIMINATING CONTROL, because a guard that
// refuses everything is not a control:
//   * refusal in place        <-> the SAME operation to a DIFFERENT directory
//                                 proceeds (test 2);
//   * refusal on a certified  <-> the SAME operation on an UNCERTIFIED source
//     source                     proceeds (test 3);
//   * refusal of an Other-class <-> an Annotation-class change on the SAME /P 3
//     change                      document is ALLOWED, in place (test 7).
//
// Fixtures: tests/fixtures/sig_iso_docmdp_p1.pdf and sig_iso_docmdp_p3.pdf,
// generated by tests/fixtures/gen_sig_shadow_corpus.py. Identical except for
// the /P value, so nothing but the certification level can explain a
// difference in outcome.

