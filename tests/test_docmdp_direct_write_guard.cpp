// ===========================================================================
// 6. ...and OptimizeEngine. run() already rejects `input == output`
//    TEXTUALLY, so the certification control has to be demonstrated on the
//    branch that survives that rejection: a write elsewhere must WARN.
//    A silent optimize of a certified document is the same defect one branch
//    over.
// ===========================================================================

TEST_F(DocMdpDirectWriteGuardTest,
       OptimizeOfACertifiedDocumentWarnsThatTheCopyBreaksCertification) {
    const auto source = stage("sig_iso_docmdp_p1.pdf", "p1_opt_src.pdf");
    const auto out = dir() / "p1_opt_out.pdf";

    pdfe::optimize::OptimizeEngine engine(ctx_);
    pdfe::optimize::OptimizeOptions opts;
    const auto result = engine.run(source, out, opts);

    ASSERT_TRUE(result.errorMessage.empty())
        << "CONTROL: optimizing to a DIFFERENT file must succeed; got: "
        << result.errorMessage;
    EXPECT_TRUE(std::filesystem::exists(out));

    const std::string warning = pdfe::signatures::lastDirectWriteWarning();
    EXPECT_FALSE(warning.empty())
        << "a full rewrite destroys the byte prefix any /ByteRange vouches "
           "for; producing it from a certified source silently is exactly the "
           "gate finding";
    EXPECT_TRUE(contains(warning, "/P 1")) << warning;
}

// ===========================================================================
// 7. THE /P-AWARENESS CONTROL — the guard's answer depends on the CHANGE
//    CLASS and the LEVEL, not merely on "is it certified".
//
//    An Annotation-class change is forbidden at /P 1 and PERMITTED at /P 3
//    (ISO 32000-1 Table 254). Both are evaluated IN PLACE, the strictest
//    branch, so the only variable is the /P value. Without this the guard
//    could be a blanket block on certified documents and every test above
//    would still pass.
// ===========================================================================

TEST_F(DocMdpDirectWriteGuardTest, AnnotationClassIsRefusedAtP1AndAllowedAtP3) {
    const auto p1 = stage("sig_iso_docmdp_p1.pdf", "p1_class.pdf");
    const auto p3 = stage("sig_iso_docmdp_p3.pdf", "p3_class.pdf");

    const auto atP1 = ask(p1, p1, DocMdpChangeClass::Annotation);
    EXPECT_TRUE(atP1.certified);
    EXPECT_EQ(static_cast<int>(atP1.level), 1);
    EXPECT_TRUE(atP1.inPlace);
    EXPECT_FALSE(atP1.allow)
        << "/P 1 permits NO change of any class (ISO 32000-1 Table 254)";

    const auto atP3 = ask(p3, p3, DocMdpChangeClass::Annotation);
    EXPECT_TRUE(atP3.certified);
    EXPECT_EQ(static_cast<int>(atP3.level), 3);
    EXPECT_TRUE(atP3.inPlace);
    EXPECT_TRUE(atP3.allow)
        << "CONTROL: /P 3 PERMITS annotation create/delete/modify. Refusing it "
           "would make this a blanket block on certified documents rather than "
           "the /P-aware control the disposition claims.";
    EXPECT_TRUE(atP3.message.empty())
        << "CONTROL: a permitted change must not even warn; got: "
        << atP3.message;

    // And the Other class — what every one of the four engines declares — is
    // refused at BOTH levels, which is why test 1's refusal is correct and why
    // /P 3 is not a loophole for a content edit.
    EXPECT_FALSE(ask(p3, p3, DocMdpChangeClass::Other).allow)
        << "a page content-stream edit is Other-class and permitted at no "
           "level, /P 3 included";
}

// ===========================================================================
// 8. The in-place decision is about the FILE, not the spelling of the path.
//    An engine invocation that dodged the refusal by writing "./name.pdf" —
//    or, on NTFS, "NAME.PDF" — would be the same bypass in a costume.
// ===========================================================================

TEST_F(DocMdpDirectWriteGuardTest, InPlaceDetectionSurvivesPathRespelling) {
    const auto target = stage("sig_iso_docmdp_p1.pdf", "p1_respell.pdf");

    const auto dotted = dir() / "." / "p1_respell.pdf";
    EXPECT_TRUE(pdfe::signatures::resolvesToSameFile(target, dotted));
    EXPECT_FALSE(ask(target, dotted, DocMdpChangeClass::Other).allow)
        << "\"./name\" names the same file and must take the in-place branch";

#ifdef _WIN32
    const auto upper = dir() / "P1_RESPELL.PDF";
    EXPECT_TRUE(pdfe::signatures::resolvesToSameFile(target, upper))
        << "NTFS is case-insensitive: this IS the same file";
    EXPECT_FALSE(ask(target, upper, DocMdpChangeClass::Other).allow);
#endif

    // CONTROL: a genuinely different name in the same directory is NOT in
    // place, and is allowed.
    const auto other = dir() / "p1_respell_copy.pdf";
    EXPECT_FALSE(pdfe::signatures::resolvesToSameFile(target, other));
    const auto v = ask(target, other, DocMdpChangeClass::Other);
    EXPECT_FALSE(v.inPlace);
    EXPECT_TRUE(v.allow)
        << "CONTROL: a different file is the warn-and-proceed branch";
    EXPECT_FALSE(v.message.empty());
}
