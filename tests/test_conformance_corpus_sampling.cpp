std::string readFileText(const fs::path& p) {
    std::ifstream in(p, std::ios::binary);
    if (!in) return {};
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

std::string sha256Hex(const std::string& bytes) {
    fz_sha256 state;
    fz_sha256_init(&state);
    fz_sha256_update(&state,
                     reinterpret_cast<const unsigned char*>(bytes.data()),
                     bytes.size());
    unsigned char digest[32];
    fz_sha256_final(&state, digest);
    static const char* hex = "0123456789abcdef";
    std::string out;
    out.reserve(64);
    for (unsigned char c : digest) {
        out += hex[c >> 4];
        out += hex[c & 0x0F];
    }
    return out;
}

// Minimal extraction of `"key": "value"` / `"key": <number>` occurrences from a
// flat-enough JSON document. The two manifests this file reads are generated by
// scripts in this repository with a fixed shape; a JSON parser is not linked
// into the test binary and pulling one in for two files would be more moving
// parts than the thing under test.
std::vector<std::string> jsonStringValues(const std::string& doc,
                                          const std::string& key) {
    std::vector<std::string> out;
    const std::string needle = "\"" + key + "\": \"";
    for (std::size_t at = doc.find(needle); at != std::string::npos;
         at = doc.find(needle, at + 1)) {
        const std::size_t from = at + needle.size();
        const std::size_t end = doc.find('"', from);
        if (end == std::string::npos) break;
        out.push_back(doc.substr(from, end - from));
    }
    return out;
}

// All records of `objectsKey`, each as the substring between one occurrence of
// `"path"`-like anchor and the next. Simpler: split the array text on "},".
std::vector<std::string> jsonRecords(const std::string& doc,
                                     const std::string& arrayKey) {
    std::vector<std::string> out;
    const std::size_t at = doc.find("\"" + arrayKey + "\": [");
    if (at == std::string::npos) return out;
    std::size_t i = doc.find('[', at);
    int depth = 0;
    std::size_t recStart = std::string::npos;
    for (; i < doc.size(); ++i) {
        const char c = doc[i];
        if (c == '{') {
            if (depth == 0) recStart = i;
            ++depth;
        } else if (c == '}') {
            --depth;
            if (depth == 0 && recStart != std::string::npos) {
                out.push_back(doc.substr(recStart, i - recStart + 1));
                recStart = std::string::npos;
            }
        } else if (c == ']' && depth == 0) {
            break;
        }
    }
    return out;
}

std::string jsonField(const std::string& record, const std::string& key) {
    const auto v = jsonStringValues(record, key);
    return v.empty() ? std::string() : v.front();
}

std::set<std::string> corpusPdfsOnDisk(const fs::path& root, bool recursive) {
    std::set<std::string> out;
    std::error_code ec;
    if (!fs::exists(root, ec)) return out;
    if (recursive) {
        for (auto it = fs::recursive_directory_iterator(root, ec);
             it != fs::recursive_directory_iterator(); it.increment(ec)) {
            if (ec) break;
            if (!it->is_regular_file()) continue;
            if (it->path().extension() != ".pdf") continue;
            out.insert(fs::relative(it->path(), root).generic_string());
        }
    } else {
        for (auto it = fs::directory_iterator(root, ec);
             it != fs::directory_iterator(); it.increment(ec)) {
            if (ec) break;
            if (!it->is_regular_file()) continue;
            if (it->path().extension() != ".pdf") continue;
            out.insert(it->path().filename().generic_string());
        }
    }
    return out;
}

// Open @p pdf and report (opened, pageCount, wasRepaired). Never throws.
struct OpenOutcome {
    bool opened = false;
    int pages = 0;
    bool repaired = false;
    std::string error;
};

OpenOutcome probeOpen(const std::shared_ptr<pdfe::core::MuPdfContext>& ctxHolder,
                      const fs::path& pdf) {
    OpenOutcome o;

    // (a) the product's own open path: does PDFE get a usable document?
    auto doc = pdfe::core::Document::open(ctxHolder, pdf);
    if (!doc) {
        o.error = "Document::open returned null";
        return o;
    }
    o.opened = true;
    o.pages = doc->pageCount();
    doc.reset();

    // (b) the repair flag. `Document::fzDocument()` is private and this test is
    // not a friend, so the file is opened a second time straight through MuPDF.
    // That is not a workaround so much as the right thing: `pdf_was_repaired`
    // is a property of the FILE, and reading it through an independent open
    // means it cannot be perturbed by anything PDFE did to the document.
    //
    // setjmp/longjmp discipline (GitHub #118): nothing with a non-trivial
    // destructor is constructed inside the fz_try block -- `path` is captured
    // as a raw pointer to storage that outlives it.
    const std::string pathStr = pdf.string();
    const char* pathC = pathStr.c_str();
    int repaired = 0;
    int failed = 0;
    ctxHolder->execute([&](fz_context* ctx) {
        pdf_document* pdfDoc = nullptr;
        fz_try(ctx) {
            pdfDoc = pdf_open_document(ctx, pathC);
            if (pdfDoc != nullptr) {
                // Page counting is what forces the xref to be resolved, and
                // therefore what makes the repair flag meaningful. Reading the
                // flag off a lazily-opened document would report 0 for a file
                // that is about to be repaired.
                (void)pdf_count_pages(ctx, pdfDoc);
                repaired = pdf_was_repaired(ctx, pdfDoc);
            }
        }
        fz_always(ctx) {
            if (pdfDoc != nullptr) pdf_drop_document(ctx, pdfDoc);
        }
        fz_catch(ctx) {
            failed = 1;
        }
    });
    o.repaired = repaired != 0;
    if (failed != 0 && o.error.empty()) {
        o.error = "pdf_open_document threw (the document opened through "
                  "Document::open, so this is a second-open failure)";
    }
    return o;
}

class ConformanceCorpusSamplingTest : public ::testing::Test {
protected:
    void SetUp() override {
        context_ = std::make_shared<pdfe::core::MuPdfContext>();
    }
    void TearDown() override { context_.reset(); }
    std::shared_ptr<pdfe::core::MuPdfContext> context_;
};

// ---------------------------------------------------------------------------
// 1. The corpus is its manifest: no unlisted file, no phantom entry.
// ---------------------------------------------------------------------------

TEST_F(ConformanceCorpusSamplingTest, EveryFixtureIsListedInTheManifestExactlyOnce) {
    const std::string manifest = readFileText(conformanceDir() / "manifest.json");
    ASSERT_FALSE(manifest.empty())
        << "tests/fixtures/flaw_corpus/conformance/manifest.json is missing or "
           "unreadable; regenerate with "
           "`python tests/fixtures/gen_conformance_corpus.py`";

    const auto records = jsonRecords(manifest, "fixtures");
    ASSERT_FALSE(records.empty())
        << "parsed ZERO fixture records out of the manifest. A check that "
           "parses nothing passes vacuously.";

    std::set<std::string> listed;
    for (const auto& r : records) {
        const std::string path = jsonField(r, "path");
        ASSERT_FALSE(path.empty()) << "a manifest record has no \"path\": " << r;
        EXPECT_TRUE(listed.insert(path).second)
            << path << " is listed twice in the manifest";
    }

    // The security_subset/ directory is COPIED material with its own manifest
    // (selection-report.json), so it is excluded here and covered by the #37
    // cases below. Excluding it by name is deliberate and asserted: if the
    // directory disappears, the #37 cases fail rather than this one silently
    // widening.
    std::set<std::string> disk;
    for (const auto& rel : corpusPdfsOnDisk(conformanceDir(), /*recursive=*/true)) {
        if (rel.rfind("security_subset/", 0) == 0) continue;
        disk.insert(rel);
    }
    ASSERT_FALSE(disk.empty()) << "no .pdf files under " << conformanceDir().string();

    std::vector<std::string> unlisted, phantom;
    std::set_difference(disk.begin(), disk.end(), listed.begin(), listed.end(),
                        std::back_inserter(unlisted));
    std::set_difference(listed.begin(), listed.end(), disk.begin(), disk.end(),
                        std::back_inserter(phantom));

    std::ostringstream u, p;
    for (const auto& s : unlisted) u << s << " ";
    for (const auto& s : phantom) p << s << " ";
    EXPECT_TRUE(unlisted.empty())
        << "these fixtures are on disk but in no manifest record: " << u.str();
    EXPECT_TRUE(phantom.empty())
        << "the manifest lists fixtures that are not on disk: " << p.str();
}

// ---------------------------------------------------------------------------
// 2. The committed bytes are the generator's bytes.
// ---------------------------------------------------------------------------
//
// A committed binary fixture whose generator has drifted is unauditable: the
// file says one thing and the script documenting it says another. The generator
// is deterministic for exactly this reason, and records a SHA-256 per fixture.

TEST_F(ConformanceCorpusSamplingTest, EveryFixtureMatchesTheDigestItsGeneratorRecorded) {
    const std::string manifest = readFileText(conformanceDir() / "manifest.json");
    ASSERT_FALSE(manifest.empty());
    const auto records = jsonRecords(manifest, "fixtures");
    ASSERT_FALSE(records.empty());

    int verified = 0;
    for (const auto& r : records) {
        const std::string path = jsonField(r, "path");
        const std::string want = jsonField(r, "sha256");
        ASSERT_EQ(want.size(), 64u)
            << "manifest record for " << path << " has no usable sha256";
        const std::string bytes = readFileText(conformanceDir() / path);
        ASSERT_FALSE(bytes.empty()) << path << " is missing or empty";
        EXPECT_EQ(sha256Hex(bytes), want)
            << path << " does not match the digest recorded by "
               "tests/fixtures/gen_conformance_corpus.py. Either the fixture "
               "was edited by hand or the generator changed without the corpus "
               "being regenerated; run "
               "`python tests/fixtures/gen_conformance_corpus.py`.";
        ++verified;
    }
    EXPECT_EQ(verified, static_cast<int>(records.size()));
    EXPECT_GE(verified, 10) << "the clause sample is implausibly small";
}

// ---------------------------------------------------------------------------
// 3. The sample spans both standards and every fixture is a live PDF.
// ---------------------------------------------------------------------------

TEST_F(ConformanceCorpusSamplingTest, EveryFixtureOpensAndTheSampleSpansBothStandards) {
    const std::string manifest = readFileText(conformanceDir() / "manifest.json");
    ASSERT_FALSE(manifest.empty());
    const auto records = jsonRecords(manifest, "fixtures");
    ASSERT_FALSE(records.empty());

    int pdfa = 0, pdfua = 0, controls = 0, negatives = 0;
    for (const auto& r : records) {
        const std::string path = jsonField(r, "path");
        const std::string kind = jsonField(r, "kind");
        SCOPED_TRACE(path);

        const OpenOutcome o = probeOpen(context_, conformanceDir() / path);
        EXPECT_TRUE(o.opened) << path << " must open: " << o.error;
        EXPECT_EQ(o.pages, 1)
            << path << " must present exactly one page; the corpus is "
                      "single-page by construction so that a page-count "
                      "difference is never a confound";
        EXPECT_FALSE(o.repaired)
            << path << " required cross-reference RECONSTRUCTION. Every "
                       "fixture here is supposed to be structurally sound and "
                       "wrong only in the ONE conformance construct it is "
                       "named for; a file MuPDF had to repair is wrong in a "
                       "second, unintended way.";

        if (path.rfind("pdfa/", 0) == 0) ++pdfa;
        if (path.rfind("pdfua/", 0) == 0) ++pdfua;
        if (kind == "control") ++controls;
        if (kind == "clause-negative") ++negatives;
    }

    EXPECT_GE(pdfa, 10) << "the PDF/A sample is too small to be clause-sampled";
    EXPECT_GE(pdfua, 4) << "the PDF/UA sample is too small to be clause-sampled";
    EXPECT_GE(controls, 4)
        << "a corpus of negatives with no controls cannot distinguish a "
           "validator from a rejector";
    EXPECT_GE(negatives, 13);
    EXPECT_EQ(controls + negatives, static_cast<int>(records.size()))
        << "every fixture must be classified as a control or a clause-negative";
}

// ---------------------------------------------------------------------------
// 4. GitHub #37 — the copied structurally-valid subset.
// ---------------------------------------------------------------------------

TEST_F(ConformanceCorpusSamplingTest, SecuritySubsetMatchesTheSelectionReport) {
    const fs::path reportPath = securitySubsetDir() / "selection-report.json";
    const std::string report = readFileText(reportPath);
    ASSERT_FALSE(report.empty())
        << "missing " << reportPath.string() << "; regenerate with "
           "`python tests/scripts/select_structurally_valid_corpus.py`";

    const auto records = jsonRecords(report, "files");
    ASSERT_FALSE(records.empty())
        << "parsed ZERO candidate records out of the selection report";

    std::set<std::string> accepted, rejected;
    for (const auto& r : records) {
        const std::string src = jsonField(r, "source");
        ASSERT_FALSE(src.empty());
        const std::string name = fs::path(src).filename().generic_string();
        if (r.find("\"structurally_valid\": true") != std::string::npos)
            accepted.insert(name);
        else
            rejected.insert(name);
    }

    // BOTH sets must be non-empty. A selector that accepted everything is
    // indistinguishable from `return true`; one that accepted nothing is a
    // broken rule set. The Python entry point refuses to run in either state,
    // and this is the same guard applied to the committed artifact.
    ASSERT_FALSE(accepted.empty())
        << "the selection report accepts nothing";
    ASSERT_FALSE(rejected.empty())
        << "the selection report rejects nothing, so its rules never said NO "
           "on this corpus and cannot be distinguished from 'return true'";

    const std::set<std::string> onDisk =
        corpusPdfsOnDisk(securitySubsetDir(), /*recursive=*/false);

    std::vector<std::string> missing, extra;
    std::set_difference(accepted.begin(), accepted.end(), onDisk.begin(),
                        onDisk.end(), std::back_inserter(missing));
    std::set_difference(onDisk.begin(), onDisk.end(), accepted.begin(),
                        accepted.end(), std::back_inserter(extra));
    std::ostringstream m, e;
    for (const auto& s : missing) m << s << " ";
    for (const auto& s : extra) e << s << " ";

    EXPECT_TRUE(missing.empty())
        << "the selector accepted these but they were not copied into "
        << securitySubsetDir().string() << ": " << m.str();
    EXPECT_TRUE(extra.empty())
        << "these files are in the subset directory but the selector did not "
           "accept them: " << e.str();

    // The copies must be byte-identical to their sources, or "the subset of
    // tests/security/corpus/" is a claim about files that no longer exist.
    for (const auto& r : records) {
        if (r.find("\"structurally_valid\": true") == std::string::npos) continue;
        const std::string src = jsonField(r, "source");
        const std::string want = jsonField(r, "sha256");
        ASSERT_EQ(want.size(), 64u) << "no sha256 for " << src;
        const fs::path copy =
            securitySubsetDir() / fs::path(src).filename();
        const std::string bytes = readFileText(copy);
        ASSERT_FALSE(bytes.empty()) << copy.string() << " is missing or empty";
        EXPECT_EQ(sha256Hex(bytes), want)
            << copy.string() << " differs from its source "
            << src << "; the copy is supposed to BE that file";
        // and the source is still there, unchanged
        const std::string srcBytes =
            readFileText(fs::path(PDFE_REPO_ROOT) / src);
        EXPECT_EQ(sha256Hex(srcBytes), want)
            << src << " has changed since the subset was selected; re-run "
                      "tests/scripts/select_structurally_valid_corpus.py";
    }
}

// The measurement that makes the selection method more than an assertion: the
// selector reads raw bytes and knows nothing about MuPDF, so its verdicts are
// re-derived here THROUGH MuPDF and the two must agree on every candidate.
TEST_F(ConformanceCorpusSamplingTest, MuPdfAgreesWithTheByteLevelSelectorOnEveryCandidate) {
    const std::string report =
        readFileText(securitySubsetDir() / "selection-report.json");
    ASSERT_FALSE(report.empty());
    const auto records = jsonRecords(report, "files");
    ASSERT_FALSE(records.empty());

    int agreedValid = 0, agreedInvalid = 0;
    for (const auto& r : records) {
        const std::string src = jsonField(r, "source");
        const bool selectorSaysValid =
            r.find("\"structurally_valid\": true") != std::string::npos;
        SCOPED_TRACE(src + (selectorSaysValid ? " [selector: VALID]"
                                              : " [selector: REJECTED]"));

        const fs::path p = fs::path(PDFE_REPO_ROOT) / src;
        ASSERT_TRUE(fs::exists(p)) << p.string() << " is gone";

        const OpenOutcome o = probeOpen(context_, p);
        ASSERT_TRUE(o.opened)
            << src << " could not be opened at all: " << o.error;

        // MuPDF's own verdict on the same property: did it have to RECONSTRUCT
        // the cross-reference table to find the objects?
        const bool mupdfSaysValid = !o.repaired && o.pages > 0;

        EXPECT_EQ(selectorSaysValid, mupdfSaysValid)
            << src << ": the byte-level selector says "
            << (selectorSaysValid ? "structurally valid" : "rejected")
            << " but MuPDF says repaired=" << o.repaired
            << " pages=" << o.pages
            << ". The two methods are independent by design; a disagreement "
               "means one of them is wrong, and the selection method in "
               "tests/scripts/select_structurally_valid_corpus.py claims they "
               "agree on this corpus.";
        if (selectorSaysValid && mupdfSaysValid) ++agreedValid;
        if (!selectorSaysValid && !mupdfSaysValid) ++agreedInvalid;
    }

    // Guard that the measurement HAPPENED and that it discriminated. Agreement
    // on an all-valid or all-invalid population would be agreement about
    // nothing.
    EXPECT_GE(agreedValid, 1)
        << "no candidate was agreed structurally valid";
    EXPECT_GE(agreedInvalid, 1)
        << "no candidate was agreed structurally INVALID, so this case never "
           "exercised the direction that matters -- it would pass against a "
           "selector that accepts everything";
}

// The copied files are the reason #37 exists: something downstream must be able
// to treat them as parsed input. This is that assertion.
TEST_F(ConformanceCorpusSamplingTest, EveryCopiedFileParsesAsStructurallyValid) {
    const std::set<std::string> onDisk =
        corpusPdfsOnDisk(securitySubsetDir(), /*recursive=*/false);
    ASSERT_FALSE(onDisk.empty())
        << "no .pdf in " << securitySubsetDir().string();

    for (const auto& name : onDisk) {
        SCOPED_TRACE(name);
        const OpenOutcome o = probeOpen(context_, securitySubsetDir() / name);
        EXPECT_TRUE(o.opened) << name << " must open: " << o.error;
        EXPECT_GT(o.pages, 0) << name << " must present at least one page";
        EXPECT_FALSE(o.repaired)
            << name << " required cross-reference reconstruction, so it is NOT "
                       "structurally valid and must not be in this subset";
    }
}

// The negative control for the whole of #37: at least one file in the source
// corpus must FAIL the property, and must still be present there. Without it,
// "the structurally-valid subset" could be the whole corpus under a different
// name.
TEST_F(ConformanceCorpusSamplingTest, AtLeastOneRejectedFileIsDemonstrablyNotStructurallyValid) {
    const std::string report =
        readFileText(securitySubsetDir() / "selection-report.json");
    ASSERT_FALSE(report.empty());
    const auto records = jsonRecords(report, "files");
    ASSERT_FALSE(records.empty());

    // No assertion sits inside a conditional here on purpose: everything is
    // accumulated first and asserted unconditionally afterwards, so there is no
    // branch on which this case can go quiet.
    int demonstrated = 0;
    std::vector<std::string> copiedDespiteRejection;
    for (const auto& r : records) {
        if (r.find("\"structurally_valid\": true") != std::string::npos) continue;
        const std::string src = jsonField(r, "source");
        const fs::path p = fs::path(PDFE_REPO_ROOT) / src;
        if (!fs::exists(p)) continue;

        const OpenOutcome o = probeOpen(context_, p);
        const bool notStructurallyValid = !o.opened || o.repaired || o.pages == 0;
        demonstrated += notStructurallyValid ? 1 : 0;
        const bool wasCopied = fs::exists(securitySubsetDir() / p.filename());
        if (notStructurallyValid && wasCopied) copiedDespiteRejection.push_back(src);
    }

    std::ostringstream leaked;
    for (const auto& s : copiedDespiteRejection) leaked << s << " ";
    EXPECT_TRUE(copiedDespiteRejection.empty())
        << "these files need cross-reference repair yet a copy of each is in "
           "the structurally-valid subset: " << leaked.str();
    EXPECT_GE(demonstrated, 1)
        << "not one rejected candidate could be shown to fail the property. "
           "Either the corpus no longer contains a malformed file, or the "
           "selection method is not discriminating -- both make the 'subset' "
           "claim empty.";
}

