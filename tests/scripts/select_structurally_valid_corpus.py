# -*- coding: utf-8 -*-
"""Select the structurally-valid subset of tests/security/corpus/ — GitHub #37.

WHAT THIS IS FOR
----------------
`tests/security/corpus/` is a *malformed-input* corpus: its job is to be
hostile.  Some of its files are nevertheless perfectly well-formed PDFs that
happen to carry a dangerous FEATURE (JavaScript, a /Launch action, an odd filter
chain) rather than a broken STRUCTURE.  Those are useful as conformance and
round-trip fixtures, because a test can legitimately expect them to parse.  The
rest cannot be used that way: a file that only opens because MuPDF rebuilt its
cross-reference table is not a file any oracle should treat as "parsed".

#37 asks for that subset to be identified by a **documented, reviewable
selection method** rather than by someone's judgement, and copied into the flaw
corpus.  This script is that method.

THE METHOD, IN FULL
-------------------
Population: every `*.pdf` under `tests/security/corpus/` **that git tracks**.

  Why git-tracked, and what it excludes.  `tests/security/corpus/malicious_pdf/`
  is excluded in its entirety, and that is deliberate rather than incidental.
  Those payloads are generated by `scripts/security/gen_malicious_corpus.ps1`
  and are gitignored on purpose -- `tests/security/corpus/README.md` gives three
  reasons (contributor antivirus, GitHub malware scanning, accidental opening
  outside the sandbox).  Copying any of them into `tests/fixtures/`, which IS
  tracked, would commit exactly the material that README refuses to commit, and
  would also make the selection non-reproducible: which payloads exist on a
  given machine depends on what the local antivirus ate.  "git tracks it" is
  therefore both the reproducibility rule and the safety rule, and it is applied
  mechanically, not by naming the directory.

Each candidate is then scored against six rules, evaluated on RAW BYTES with no
PDF library involved.  Using a parser would beg the question: the point is to
decide whether a parser should have to guess, so the check must be independent
of any parser's recovery behaviour.

  S1  the file begins with `%PDF-1.x` (or `%PDF-2.x`) at offset 0.
  S2  the file contains `%%EOF`.
  S3  the file contains a `startxref` whose integer operand is inside the file.
  S4  the bytes at that offset are a cross-reference section that parses
      STRICTLY: either
        (a) the keyword `xref`, then one or more `<start> <count>` subsection
            headers each followed by exactly `count` 20-byte entries of the form
            `nnnnnnnnnn ggggg n|f`, terminated by `trailer`; every subsection
            must satisfy `start + count <= /Size`; or
        (b) an indirect-object header `N G obj` introducing a stream dictionary
            with `/Type /XRef` (a cross-reference stream).
  S5  a `/Root` entry is present in the trailer dictionary (or in the xref
      stream dictionary).
  S6  at least one `/Type /Page` object is present.

A file is STRUCTURALLY VALID iff all six hold.  Anything else is REJECTED, with
the failing rule ids recorded so the decision is reviewable rather than a bare
verdict.

WHAT THE RULES ARE NOT.  They do not establish that a file is *safe*, or that it
renders, or that it is semantically correct.  They establish that a conforming
reader does not have to RECONSTRUCT anything to find the objects -- which is the
only property #37's downstream test asserts.

CROSS-CHECK.  The verdicts here were derived independently of MuPDF and then
compared against MuPDF's own `is_repaired` flag over the same eight files; the
two agree on all eight.  That agreement is what makes this a measurement rather
than a restatement, and `tests/test_conformance_corpus_sampling.cpp` re-runs the
MuPDF half on every suite run so the two cannot silently diverge.

Usage:
    python tests/scripts/select_structurally_valid_corpus.py            # copy
    python tests/scripts/select_structurally_valid_corpus.py --check    # verify
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
CORPUS = REPO / "tests" / "security" / "corpus"
DEST = REPO / "tests" / "fixtures" / "flaw_corpus" / "conformance" / "security_subset"
REPORT = DEST / "selection-report.json"

RULES = ("S1", "S2", "S3", "S4", "S5", "S6")


# ---------------------------------------------------------------------------
# The six rules
# ---------------------------------------------------------------------------

_XREF_ENTRY = re.compile(rb"^\d{10} \d{5} [nf]")
_SUBSECTION = re.compile(rb"^(\d+)\s+(\d+)\s*$")
_OBJ_HEADER = re.compile(rb"^\d+\s+\d+\s+obj\b")


def _trailer_size(data: bytes) -> int | None:
    m = None
    for m in re.finditer(rb"/Size\s+(\d+)", data):
        pass
    return int(m.group(1)) if m else None


def _check_xref_table(data: bytes, at: int, size: int | None) -> bool:
    """S4(a): a classic cross-reference table that parses strictly."""
    lines = data[at:].split(b"\n")
    if not lines or lines[0].strip() != b"xref":
        return False
    i = 1
    saw_subsection = False
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if line == b"":
            continue
        if line.startswith(b"trailer"):
            return saw_subsection
        m = _SUBSECTION.match(line)
        if not m:
            return False
        start, count = int(m.group(1)), int(m.group(2))
        # A subsection that runs past /Size (or past any sane object number)
        # is the GHOSTSCRIPT-698804 shape: `00000004294967296 3`, which forces
        # a reader to reconstruct.
        if count <= 0 or start < 0 or start + count > 2**31:
            return False
        if size is not None and start + count > size:
            return False
        for _ in range(count):
            if i >= len(lines) or not _XREF_ENTRY.match(lines[i].strip()):
                return False
            i += 1
        saw_subsection = True
    return False


def _check_xref_stream(data: bytes, at: int) -> bool:
    """S4(b): an indirect object at `at` whose dictionary is /Type /XRef."""
    head = data[at:at + 512]
    if not _OBJ_HEADER.match(head.lstrip()):
        return False
    return b"/XRef" in head


def evaluate(data: bytes) -> dict[str, bool]:
    res: dict[str, bool] = {}

    res["S1"] = bool(re.match(rb"^%PDF-[12]\.\d", data))
    res["S2"] = b"%%EOF" in data

    at = -1
    m = None
    for m in re.finditer(rb"startxref\s+(\d+)", data):
        pass
    if m is not None:
        at = int(m.group(1))
    res["S3"] = at >= 0 and at < len(data)

    if res["S3"]:
        size = _trailer_size(data)
        res["S4"] = _check_xref_table(data, at, size) or _check_xref_stream(data, at)
    else:
        res["S4"] = False

    res["S5"] = re.search(rb"/Root\s+\d+\s+\d+\s+R", data) is not None
    res["S6"] = re.search(rb"/Type\s*/Page[^s]", data) is not None
    return res


# ---------------------------------------------------------------------------
# Population + driver
# ---------------------------------------------------------------------------

def tracked_corpus_pdfs() -> list[pathlib.Path]:
    out = subprocess.run(
        ["git", "ls-files", "--", "tests/security/corpus"],
        cwd=REPO, capture_output=True, text=True, encoding="utf-8", check=True)
    paths = []
    for line in out.stdout.splitlines():
        rel = line.strip()
        if rel.lower().endswith(".pdf"):
            paths.append(REPO / rel)
    return sorted(paths, key=lambda p: p.as_posix())


def build() -> tuple[list[dict], str]:
    records: list[dict] = []
    for p in tracked_corpus_pdfs():
        data = p.read_bytes()
        rules = evaluate(data)
        records.append({
            "source": p.relative_to(REPO).as_posix(),
            "size": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "rules": rules,
            "failed_rules": [r for r in RULES if not rules[r]],
            "structurally_valid": all(rules.values()),
        })

    accepted = [r for r in records if r["structurally_valid"]]
    report = {
        "_what": "Selection of the structurally-valid subset of "
                 "tests/security/corpus/ (GitHub #37).",
        "_method": "tests/scripts/select_structurally_valid_corpus.py -- read "
                   "its module docstring for the six rules and for why "
                   "malicious_pdf/ is out of the population.",
        "_not_claimed": "Structural validity is NOT safety, renderability or "
                        "semantic correctness. It means only that a conforming "
                        "reader need not RECONSTRUCT the cross-reference table.",
        "rules": {
            "S1": "%PDF-1.x / %PDF-2.x header at offset 0",
            "S2": "%%EOF present",
            "S3": "startxref operand is inside the file",
            "S4": "the xref section at that offset parses strictly "
                  "(table with in-range subsections, or an /Type /XRef stream)",
            "S5": "/Root present in a trailer or xref-stream dictionary",
            "S6": "at least one /Type /Page object",
        },
        "population": "git-tracked *.pdf under tests/security/corpus/",
        "candidates": len(records),
        "accepted": len(accepted),
        "rejected": len(records) - len(accepted),
        "destination": DEST.relative_to(REPO).as_posix(),
        "files": records,
    }
    return records, json.dumps(report, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    records, report = build()
    accepted = [r for r in records if r["structurally_valid"]]

    if not records:
        print("select_structurally_valid_corpus: FAIL -- the population is "
              "EMPTY; a selector that scanned nothing accepts nothing and "
              "would pass vacuously")
        return 1
    if not accepted:
        print("select_structurally_valid_corpus: FAIL -- every candidate was "
              "rejected; that is a broken rule set, not a finding")
        return 1
    if len(accepted) == len(records):
        print("select_structurally_valid_corpus: FAIL -- every candidate was "
              "accepted, so the rules never said NO on this corpus and cannot "
              "be distinguished from 'return True'")
        return 1

    if args.check:
        bad = 0
        want = {pathlib.Path(r["source"]).name for r in accepted}
        have = {p.name for p in DEST.glob("*.pdf")}
        for name in sorted(want - have):
            print(f"MISSING {name}")
            bad += 1
        for name in sorted(have - want):
            print(f"UNEXPECTED {name} (not selected, but present)")
            bad += 1
        for r in accepted:
            d = DEST / pathlib.Path(r["source"]).name
            if d.exists() and hashlib.sha256(d.read_bytes()).hexdigest() != r["sha256"]:
                print(f"DRIFTED {d.name}")
                bad += 1
        if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != report:
            print("DRIFTED selection-report.json")
            bad += 1
        print(f"select_structurally_valid_corpus --check: "
              f"{len(records)} candidate(s), {len(accepted)} accepted, "
              f"{bad} mismatch(es)")
        return 1 if bad else 0

    DEST.mkdir(parents=True, exist_ok=True)
    for r in accepted:
        src = REPO / r["source"]
        (DEST / src.name).write_bytes(src.read_bytes())
    REPORT.write_text(report, encoding="utf-8")
    print(f"select_structurally_valid_corpus: {len(records)} candidate(s), "
          f"{len(accepted)} accepted, {len(records) - len(accepted)} rejected "
          f"-> {DEST}")
    for r in records:
        if not r["structurally_valid"]:
            print(f"  rejected {pathlib.Path(r['source']).name:40s} "
                  f"failed {','.join(r['failed_rules'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
