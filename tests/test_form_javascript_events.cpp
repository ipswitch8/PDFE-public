using pdfe::core::Document;
using pdfe::core::MuPdfContext;
using pdfe::core::Page;
using pdfe::forms::FormManager;
using pdfe::forms::JavaScriptEngine;

namespace {

class FormAaEventsTest : public ::testing::Test {
protected:
    void SetUp() override
    {
        const auto fixture =
            std::filesystem::path(TEST_FIXTURES_DIR) / "form_aa_events.pdf";
        ASSERT_TRUE(std::filesystem::exists(fixture))
            << "committed fixture missing: " << fixture
            << " (regenerate with tests/fixtures/gen_form_aa_events.py)";

        ctx_ = std::make_shared<MuPdfContext>();
        doc_ = Document::open(ctx_, fixture);
        ASSERT_NE(doc_, nullptr);
        pageOwner_ = doc_->page(0);
        ASSERT_NE(pageOwner_, nullptr);
        page_ = pageOwner_.get();

        mgr_ = std::make_unique<FormManager>(ctx_);
        engine_ = std::make_unique<JavaScriptEngine>(ctx_);
        engine_->enable(page_);
        ASSERT_TRUE(engine_->isEnabled())
            << "JavaScript is not enabled, so every assertion below would be "
               "measuring a bridge that was never switched on.";

        fields_ = mgr_->getFormFields(page_);
        ASSERT_EQ(fields_.size(), 4u) << "fixture authors exactly four fields.";
    }

    void TearDown() override
    {
        engine_.reset();
        mgr_.reset();
        pageOwner_.reset();
        doc_.reset();
        ctx_.reset();
    }

    int indexOf(const std::string& name) const
    {
        for (const auto& f : fields_) {
            if (f.fieldName == name) return f.widgetIndex;
        }
        return -1;
    }

    std::string valueOf(int widgetIndex)
    {
        return mgr_->getFormField(page_, widgetIndex).value;
    }

    std::shared_ptr<MuPdfContext> ctx_;
    std::unique_ptr<Document> doc_;
    std::unique_ptr<Page> pageOwner_;
    Page* page_ = nullptr;
    std::unique_ptr<FormManager> mgr_;
    std::unique_ptr<JavaScriptEngine> engine_;
    std::vector<pdfe::forms::FormFieldData> fields_;
};

}  // namespace

// ===========================================================================
// FormatActionRewritesDisplayValue
// ===========================================================================
//
// The Format action's job is to produce the DISPLAY value from the stored
// value. The assertion is on the exact transformed string, never on "the
// result is non-empty" or "the result contains the digits" — both of those
// hold for a bridge that echoes /V and therefore prove nothing.
TEST_F(FormAaEventsTest, FormatActionRewritesDisplayValue)
{
    const int iAmount = indexOf("Amount");
    const int iNone = indexOf("NoFormatAction");
    ASSERT_GE(iAmount, 0);
    ASSERT_GE(iNone, 0);

    struct Case {
        const char* stored;
        const char* displayed;
    };
    // Each output differs from its input by a currency sign, and all but one
    // also by grouping and/or a forced second decimal place.
    const Case cases[] = {
        {"1234567.5", "$1,234,567.50"},
        {"1000",      "$1,000.00"},
        {"89.1",      "$89.10"},
        {"0",         "$0.00"},
        {"-42",       "-$42.00"},
    };

    for (const auto& c : cases) {
        mgr_->setFieldValue(page_, iAmount, c.stored);
        ASSERT_EQ(valueOf(iAmount), std::string(c.stored))
            << "precondition: the raw value must be stored verbatim, or the "
               "comparison below is not measuring the Format action.";

        const std::string displayed = engine_->fireFormatEvent(page_, iAmount);

        EXPECT_EQ(displayed, std::string(c.displayed))
            << "the /AA /F Format action did not rewrite the display value: "
               "stored '" << c.stored << "', expected '" << c.displayed
            << "', got '" << displayed << "'";

        // The discriminator, spelled out: a bridge that never executed the
        // script would hand back the raw value (or nothing). Both are wrong
        // for EVERY case above by construction.
        EXPECT_NE(displayed, std::string(c.stored))
            << "the display value is byte-identical to the stored value, "
               "which is exactly what a no-op MuJS bridge produces";
        EXPECT_FALSE(displayed.empty())
            << "the Format action produced nothing; an unexecuted script and "
               "a missing action are indistinguishable here";

        // The Format action must not write back through /V. Display-only.
        EXPECT_EQ(valueOf(iAmount), std::string(c.stored))
            << "firing the Format action mutated the STORED value; the "
               "formatted string is a display artefact only";
    }

    // NEGATIVE CONTROL. Same engine, same document, same raw value — but this
    // field authors no /AA at all, so there is nothing to run and the display
    // value is empty. Without this, an implementation that currency-formatted
    // every text field it was handed would pass everything above.
    mgr_->setFieldValue(page_, iNone, "1234567.5");
    EXPECT_EQ(engine_->fireFormatEvent(page_, iNone), std::string())
        << "a field with no /AA /F Format action reported a formatted value; "
           "the rewrite is not coming from the authored script";
}

// ===========================================================================
// KeystrokeActionRejectsInvalidChar
// ===========================================================================
//
// Three properties, and all three are needed:
//   1. an invalid character is REJECTED and the field value does not change;
//   2. a valid character is ACCEPTED and the field value does change —
//      without this, "rejects everything" is a passing implementation;
//   3. a keystroke script that REWRITES its input has its rewrite stored —
//      acceptance alone is unfalsifiable, a rewrite is not.
TEST_F(FormAaEventsTest, KeystrokeActionRejectsInvalidChar)
{
    const int iDigits = indexOf("DigitsOnly");
    const int iUpper = indexOf("UpperCase");
    ASSERT_GE(iDigits, 0);
    ASSERT_GE(iUpper, 0);

    // ── The raw event verdict, both directions. ──────────────────────────
    EXPECT_EQ(engine_->fireKeystrokeEvent(page_, iDigits, "12", "a", 2, 2, false), 0)
        << "the /AA /K action accepted the non-digit 'a'; a bridge that never "
           "runs the script returns 1 for everything, which is this exact "
           "failure";
    EXPECT_EQ(engine_->fireKeystrokeEvent(page_, iDigits, "12", "!", 2, 2, false), 0)
        << "the /AA /K action accepted the punctuation '!'";
    EXPECT_NE(engine_->fireKeystrokeEvent(page_, iDigits, "12", "3", 2, 2, false), 0)
        << "the /AA /K action rejected the digit '3'; a bridge that rejects "
           "everything satisfies the rejection half above and is just as "
           "broken";
    EXPECT_NE(engine_->fireKeystrokeEvent(page_, iDigits, "12", "", 2, 2, true), 0)
        << "the commit pass (empty change) must be accepted, or no valid "
           "value could ever be committed";

    // ── The verdict actually gates the stored value. ─────────────────────
    ASSERT_EQ(valueOf(iDigits), std::string())
        << "precondition: the fixture starts DigitsOnly empty.";

    EXPECT_FALSE(engine_->commitTextFieldValue(page_, iDigits, "12a"))
        << "committing a value containing a non-digit through the keystroke "
           "path must be refused";
    EXPECT_EQ(valueOf(iDigits), std::string())
        << "a REJECTED keystroke still wrote the value into the field -- the "
           "rejection is advisory only, which is the defect this test exists "
           "for";

    EXPECT_TRUE(engine_->commitTextFieldValue(page_, iDigits, "123"))
        << "a value the script accepts must commit";
    EXPECT_EQ(valueOf(iDigits), std::string("123"))
        << "an ACCEPTED keystroke did not store its value; a bridge that "
           "refuses everything would pass the rejection assertions above";

    // ── A rewriting script proves execution, not merely permission. ──────
    ASSERT_EQ(valueOf(iUpper), std::string())
        << "precondition: the fixture starts UpperCase empty.";
    EXPECT_TRUE(engine_->commitTextFieldValue(page_, iUpper, "abc"));
    EXPECT_EQ(valueOf(iUpper), std::string("ABC"))
        << "the /AA /K script rewrote event.change to upper case and the "
           "field stored '" << valueOf(iUpper) << "'. Lower-case 'abc' means "
           "the script did not run: no no-op bridge can turn 'abc' into "
           "'ABC', so this is the sharpest working-vs-no-op discriminator in "
           "the file";

    // The DigitsOnly field is untouched by the UpperCase commit — the actions
    // are per-field, not a document-wide filter.
    EXPECT_EQ(valueOf(iDigits), std::string("123"));
}
