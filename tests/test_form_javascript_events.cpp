// PDF-46 (meta-audit-2026-07 gap register) / GitHub issue #17 —
// {FormatActionRewritesDisplayValue, KeystrokeActionRejectsInvalidChar}.
//
// WHAT WAS WRONG. The suite fired /AA Format and Keystroke events in a dozen
// places and never once asserted a SEMANTIC outcome. Every one of those
// oracles was satisfiable by a MuJS bridge that executed nothing:
//
//   test_javascript_engine.cpp    "call fireFormatEvent twice, get the same
//                                 answer" — determinism. A bridge returning
//                                 the empty string is perfectly deterministic.
//   test_form_javascript_xss.cpp  "does not throw / returns a decision" on
//                                 hostile input — a safety property, not a
//                                 functional one. Accept-everything passes.
//   test_form_actions.cpp         fires a keystroke and discards the result.
//
// So "PDFE runs form JavaScript" was, for Format and Keystroke, an untested
// claim. (Validate was repaired earlier by A1-60; see test_forms_phase5.cpp.)
//
// THE REPAIR, and the one property that matters. tests/fixtures/
// form_aa_events.pdf (generated by tests/fixtures/gen_form_aa_events.py)
// authors real /AA /F and /AA /K actions whose OUTPUT IS NECESSARILY
// DIFFERENT FROM THEIR INPUT:
//
//   * the Format action turns "1234567.5" into "$1,234,567.50" — it gains a
//     currency sign, thousands separators AND a forced second decimal, so no
//     no-op, echo or truncation can produce it;
//   * one Keystroke action REJECTS a non-digit and ACCEPTS a digit (both
//     directions, so neither an accept-everything nor a reject-everything
//     bridge survives);
//   * the other Keystroke action REWRITES the change to upper case, and the
//     rewritten value is what lands in /V — unreachable without execution.
//
// MUTATIONS KILLED (each confirmed RED, then reverted — see
// docs/audit/p84-remaining-open/phase-6/notes-forms.md):
//   * no-op the format bridge (`return formatted;` -> `return std::string();`
//     / echo the raw /V) -> FormatActionRewritesDisplayValue fails on the
//     "$1,234,567.50" assertion.
//   * no-op the keystroke bridge (fireKeystrokeEvent -> `return 1;`)
//     -> KeystrokeActionRejectsInvalidChar fails on the rejection assertion.
//   * no-op the commit bridge (commitTextFieldValue -> pdf_set_field_value
//     with ignore_trigger_events=1) -> the rejected value lands in /V and the
//     UpperCase rewrite never happens; both halves fail.

