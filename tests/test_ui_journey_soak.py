"""Cumulative single-session "journey" soak (pipeline f4a82c1e Phase 2).

ONE long-lived PDFE process is driven through a long, diverse, realistic
operation sequence on ONE document — the *journey* — with named CHECKPOINTS
interspersed. At every checkpoint the harness asserts the cumulative
invariants I-1..I-5 defined in
``tests/docs/testing-methodology-cumulative-single-session.md``:

  I-1  process alive (no crash / abort / hang)
  I-2  resource bounded (RSS / handles / threads not monotonically unbounded)
  I-3  undo -> clean (a reversible probe returns to its pre-probe state)
  I-4  save -> reopen -> re-extract integrity (edits land, file reopens, no
       corruption / no lost changes)
  I-5  tile/store sanity under editing (an edited page's saved content
       reflects the edit; render path exercised without a stale-tile crash)

This is the methodology the fresh-session-per-test suite is structurally
unable to run: 290 launches across 42 files, one operation each, cannot
observe anything that accrues *across* operations (the class that produced
bug #6). The primary discovery target is the still-open render-lifetime race
(`3e91a7c4` closure `B-1`): a dirtying edit calls ``refreshAllPages()`` ->
``cancelAll()`` WITHOUT joining in-flight render workers, then a scroll runs
``pdf_drop_page_tree()`` while a worker is still inside
``fz_run_display_list()`` -> use-after-free.

Targets (see ``TARGETS`` below):
  * the committed CI-portable corpus (``tests/fixtures/journey_corpus.pdf``,
    generated by ``make_journey_corpus.py``) — ALWAYS present, non-skippable.
  * the real 51-page "SpecimenA Green" user PDF — SKIPPED when absent.

Op budget is env-tunable so the same harness serves a bounded CI lane and an
extended nightly run:
  JOURNEY_OP_BUDGET   total operations to perform (default 120)
  JOURNEY_BATCH       ops between checkpoints (default 18)

A machine-readable findings report is written to
``tests/_runtime/journey_findings_<target>.json`` for the Phase 2 discovery
report and the Phase 4 CI lane.

Run:  python -m pytest tests/test_ui_journey_soak.py -v -s
"""
