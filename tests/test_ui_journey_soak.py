class JourneyDriver:
    """Drives ONE long-lived PDFE session through the op vocabulary via the
    deterministic test pipes, recording checkpoints and any invariant
    violations as structured findings."""

    def __init__(self, session, target_name: str, page_count: int):
        self.s = session
        self.target = target_name
        self.page_count = max(1, page_count)
        self.op_count = 0
        self.checkpoints: list[dict] = []
        self.findings: list[dict] = []
        self._annot_types = ["Highlight", "Square", "Circle", "Text", "Underline"]
        # page -> count of annotations this journey has created on it, so
        # move/delete ops can target a page that actually has one (index 0).
        self._annots_on: dict[int, int] = {}

    # ---- process / resource oracles ------------------------------------

    def alive(self) -> bool:
        from tests.helpers.pdfe_session import list_pdfe_pids
        try:
            return self.s.pid in list_pdfe_pids()
        except Exception:  # noqa: BLE001
            return False

    def _snapshot(self) -> dict:
        import psutil
        try:
            p = psutil.Process(self.s.pid)
            m = p.memory_info()
            return {
                "rss_mb": round(m.rss / (1024 * 1024), 1),
                "handles": getattr(p, "num_handles", lambda: 0)(),
                "threads": p.num_threads(),
            }
        except Exception:  # noqa: BLE001
            return {"rss_mb": 0.0, "handles": 0, "threads": 0}

    def finding(self, severity: str, invariant: str, detail: str) -> None:
        rec = {
            "target": self.target,
            "op_count": self.op_count,
            "severity": severity,      # crash|corruption|lost-change|leak|undo|stale-tile
            "invariant": invariant,    # I-1..I-5
            "detail": detail,
        }
        self.findings.append(rec)
        print(f"  [FINDING/{severity}/{invariant}] op={self.op_count}: {detail}")

    # ---- op primitives (via qinvoke / pipes) ---------------------------

    def _write(self, auto_id: str, value: str, settle: float = 0.25) -> bool:
        from tests.helpers import qinvoke
        return qinvoke._write_to_pipe(self.s, auto_id, value, settle=settle)

    def goto(self, idx: int) -> None:
        self._write("testGoToPagePipe", str(idx % self.page_count))
        self.op_count += 1

    def scroll(self, delta: int) -> None:
        self._write("testScrollPipe", str(delta), settle=0.05)
        self.op_count += 1

    def scroll_whole_document(self) -> None:
        """Sweep every page, then home (render coverage).

        This was the *trigger* half of the B-1 armed-crash probe and used
        settle=0.02 to hammer scrolls faster than the render workers could
        drain. B-1 is REFUTED and the real save/rebind hazard fixed, so that
        pathological timing serves no purpose; a small settle keeps the render
        pump from being pounded flat without slowing the sweep much.

        Do NOT call wait_for_idle() (or any other UIA query) inside this loop:
        it re-resolves the window via pywinauto (find_element -> FindAll), a
        cross-process COM call that can block while PDFE's message pump is busy
        repainting — i.e. it ADDS a hang risk in the exact window it was meant to
        protect. Plain time.sleep (via ``settle``) drains the pump without
        touching UIA.
        """
        for _ in range(self.page_count + 5):
            self._write("testScrollPipe", "700", settle=0.1)
        self._write("testGoToPagePipe", "0", settle=0.15)
        self.op_count += 1

    def armed_race_burst(self, rounds: int = 8) -> None:
        """Dirty-edit + whole-doc-sweep bursts (render churn coverage).

        Originally a zero-settle probe to hunt the B-1 render-lifetime race
        (a dirtying edit -> refreshAllPages()->cancelAll() without joining
        in-flight render workers, then a scroll that drops the page tree while
        a worker is mid fz_run_display_list). B-1 is REFUTED and the real
        hazard fixed, so the settle=0.0 hammering no longer serves a discovery
        purpose — and its back-to-back UIA writes on a busy repaint pump hang
        SetValue on slow CI (gap-A14, write side). Use a small settle so the
        pump drains between writes while still exercising rapid edit->scroll
        churn. The process-alive (I-1) check is retained.
        """
        for r in range(rounds):
            page = (r * 5) % self.page_count
            # Dirty a page (markPageDirty + refreshAllPages -> cancelAll).
            self._write("testAnnotCreatePipe", f"Square,{page},80,120,60,18", settle=0.1)
            # Sweep the whole doc.
            for _ in range(10):
                self._write("testScrollPipe", "900", settle=0.1)
            # Jump home (another display-list rebuild).
            self._write("testGoToPagePipe", "0", settle=0.1)
            if not self.alive():
                self.finding("crash", "I-1",
                             f"process died during armed-race burst round {r} "
                             f"(page {page}) — likely B-1 render-lifetime UAF")
                raise _JourneyCrash("armed-race")
        self.op_count += 1

    def create_annot(self, page: int, i: int) -> None:
        page = page % self.page_count
        atype = self._annot_types[i % len(self._annot_types)]
        x = 72 + (i % 3) * 40
        y = 200 + (i % 5) * 30
        self._write("testAnnotCreatePipe", f"{atype},{page},{x},{y},80,20")
        self._annots_on[page] = self._annots_on.get(page, 0) + 1
        self.op_count += 1

    def small_text_edit(self, page: int) -> None:
        """Edit small body text DIRECTLY — activate the text-edit tool,
        double-click a small (8 pt) body span to word-select, type a
        replacement, commit with Escape. This drives the ContentStreamEditor
        edit path (`#4/#5`), which is DISTINCT from Replace-All's search path
        even though both ultimately write the content stream. Corpus body
        pages (type cycle index % 5 == 0) carry '...the greens simmer...' 8 pt
        spans at fitz bbox ~[72..225, 77..136]."""
        from tests.helpers import qinvoke
        bp = ((page // 5) * 5) % self.page_count   # snap to a body page
        self.goto(bp)
        self.activate("textEditToolAction")
        time.sleep(0.3)
        # Double-click a body span (fitz coords, origin top-left) to select.
        qinvoke.double_click_by_pdf_coord(self.s, bp, 100.0, 82.0)
        time.sleep(0.2)
        qinvoke.type_into_text_edit(self.s, "Z")
        time.sleep(0.2)
        qinvoke.send_key_to_text_edit(self.s, 0x01000000)  # Qt::Key_Escape -> commit/exit
        self.op_count += 1

    def _page_with_annot(self) -> int | None:
        for pg, n in self._annots_on.items():
            if n > 0 and pg < self.page_count:
                return pg
        return None

    def move_annot(self) -> None:
        """Select the first annotation on a page that has one, then drag it
        (select -> canvas drag). Exercises the annotation-move path."""
        pg = self._page_with_annot()
        if pg is None:
            return
        self._write("testAnnotSelectPipe", f"{pg},0", settle=0.15)
        # Drag by pdf-coords: "page,fromX,fromY,toX,toY".
        self._write("testCanvasDragPipe", f"{pg},110,210,180,260", settle=0.2)
        self.op_count += 1

    def delete_annot(self) -> None:
        """Select the first annotation on a page that has one, then delete it."""
        pg = self._page_with_annot()
        if pg is None:
            return
        self._write("testAnnotSelectPipe", f"{pg},0", settle=0.15)
        self._write("testAnnotDeletePipe", "1", settle=0.2)
        self._annots_on[pg] = max(0, self._annots_on.get(pg, 0) - 1)
        self.op_count += 1

    def rotate_page(self, page: int, cw: bool = True) -> None:
        """Rotate an actual page (distinct from rotating the VIEW)."""
        self.goto(page % self.page_count)
        self.activate("rotatePageCWAction" if cw else "rotatePageCCWAction")

    def delete_page(self, page: int) -> None:
        """Delete a page, then re-query the count so later ops stay in bounds.
        Guarded so the document never shrinks below a floor."""
        if self.page_count <= 4:
            return
        self.goto(page % self.page_count)
        self.activate("deletePageAction")
        time.sleep(0.4)
        pc = self.query_page_count()
        if pc and pc >= 1:
            self.page_count = pc

    def deep_undo_redo(self, k: int = 5) -> None:
        """Create k annotations, then undo k times and redo k times — a deep,
        interleaved undo/redo chain (not a single-step probe)."""
        base_pages = []
        for j in range(k):
            pg = (j * 6) % self.page_count
            self.create_annot(pg, j + 100)
            base_pages.append(pg)
        for _ in range(k):
            self.activate("undoAction")
            time.sleep(0.05)
        for _ in range(k):
            self.activate("redoAction")
            time.sleep(0.05)
        # Redo restored the annotations; keep the tracking dict consistent.
        for pg in base_pages:
            self._annots_on[pg] = self._annots_on.get(pg, 0)

    def add_redaction(self, page: int) -> None:
        self._write("testAddRedactionMarkPipe",
                    f"{page % self.page_count},100,300,120,18")
        self.op_count += 1

    def activate(self, action: str) -> bool:
        from tests.helpers import qinvoke
        ok = qinvoke.activate_tool_by_name(self.s, action)
        self.op_count += 1
        return ok

    def query_page_count(self) -> int | None:
        from tests.helpers import qinvoke
        self._write("testPageCountQueryPipe", "1", settle=0.2)
        raw = qinvoke._read_result_pipe(self.s, "testPageCountResultPipe")
        try:
            return int((raw or "").strip())
        except Exception:  # noqa: BLE001
            return None

    def save_as(self, path: Path, wait_s: float = 30.0) -> bool:
        if path.exists():
            try:
                path.unlink()
            except Exception:  # noqa: BLE001
                pass
        self._write("testSaveAsPipe", str(path), settle=0.5)
        deadline = time.time() + wait_s
        last = -1
        while time.time() < deadline:
            if path.exists():
                sz = path.stat().st_size
                if sz > 500 and sz == last:
                    return True
                last = sz
            if not self.alive():
                return False
            time.sleep(0.4)
        return path.exists() and path.stat().st_size > 500

    def replace_all(self, find: str, repl: str) -> bool:
        """Replace All via the search/replace panel — the all-page extraction
        path that armed #6.

        The fields are populated via the UIA ValuePattern (``set_edit_text``),
        NOT ``type_keys``/SendInput: on the desktop-less RDP session SendInput
        silently drops keystrokes ("SendInput() inserted only 0 out of 2"),
        which meant an earlier revision never actually exercised Replace-All.
        Failure to reach the panel widgets on a given host is NOT a defect
        (recorded as a note); a crash during it IS (caught by the checkpoint)."""
        try:
            self.activate("replaceAction")
            time.sleep(0.6)
            search = self.s.find_optional(auto_id="searchEdit", timeout=4.0)
            replace = self.s.find_optional(auto_id="replaceField", timeout=2.0)
            btn = self.s.find_optional(auto_id="replaceAllButton", timeout=2.0)
            if not (search and replace and btn):
                self.finding("note", "op",
                             "replace_all: search/replace panel widgets not found")
                return False
            ok = True
            for widget, text in ((search, find), (replace, repl)):
                wrote = False
                for method in ("set_edit_text", "set_value"):
                    try:
                        getattr(widget, method)(text)
                        wrote = True
                        break
                    except Exception:  # noqa: BLE001
                        continue
                ok = ok and wrote
            if not ok:
                self.finding("note", "op",
                             "replace_all: could not set field text via ValuePattern")
                return False
            time.sleep(0.3)
            btn.click_input()
            time.sleep(1.5)
            self.op_count += 1
            return True
        except Exception as exc:  # noqa: BLE001
            self.finding("note", "op", f"replace_all could not run: {exc!r}")
            return False

    # ---- checkpoint: I-1 + I-2 -----------------------------------------

    def checkpoint(self, label: str) -> None:
        if not self.alive():
            self.finding("crash", "I-1",
                         f"PDFE process gone at checkpoint '{label}'")
            raise _JourneyCrash(label)
        snap = self._snapshot()
        snap["label"] = label
        snap["op_count"] = self.op_count
        self.checkpoints.append(snap)
        print(f"  checkpoint '{label}' ops={self.op_count} "
              f"RSS={snap['rss_mb']}MB handles={snap['handles']} "
              f"threads={snap['threads']}")
        # gap-A14: if PDFE's UIA provider has wedged (it stops answering FindAll
        # while PDFE stays alive + WM_NULL-responsive), the harness can no longer
        # drive OR reliably observe the UI — every subsequent op fast-fails, and
        # oracles would emit false defects (e.g. "save produced no file"). Detect
        # it at the checkpoint boundary and stop with an honest inconclusive
        # note, so the journey ends promptly instead of grinding out false
        # positives. (PDFE itself is fine; this is a Server-2019 UIA limitation.)
        from tests.helpers import qinvoke  # noqa: PLC0415
        if qinvoke.is_uia_wedged(self.s):
            self.finding("note", "gap-A14",
                         f"UIA provider wedged by checkpoint '{label}' "
                         f"(op {self.op_count}); journey inconclusive from here "
                         f"— harness/platform limitation, PDFE remained alive "
                         f"and responsive to Win32 messages, not a defect.")
            raise _JourneyWedge(label)

    # ---- I-2 trend assertion (methodology: TREND, not a single before/after)

    def assert_resource_bounded(self) -> None:
        """Assess the resource TREND, warm-up-invariantly.

        When the session first goes active a one-time RAMP occurs — the render
        worker pool, tile cache, and GDI/font objects spin up — and the metric
        steps from its 'open' baseline to a much higher operating plateau. That
        ramp is EXPECTED and is NOT a leak. Crucially, the ramp does not always
        land on the first editing checkpoint: depending on which op first
        triggers a heavy render, it can land several checkpoints in. So a fixed
        "drop checkpoint 0" rule is not robust (an earlier revision false-fired
        because the ramp landed at batch 2).

        Robust rule: locate the ramp as the single largest upward step, then
        evaluate ONLY the operating window that follows it. A healthy session
        has a flat operating window regardless of when the ramp happened; a real
        leak keeps climbing THROUGH the operating window. If the operating
        window is too short to judge (ramp landed near the end), report
        inconclusive rather than guessing.
        """
        cps = self.checkpoints
        if len(cps) < 4:
            self.finding("note", "I-2",
                         f"only {len(cps)} checkpoints — I-2 trend inconclusive; "
                         f"run a larger op budget")
            return

        def trend(series, budget, name, unit):
            n = len(series)
            steps = [series[i + 1] - series[i] for i in range(n - 1)]
            # The warm-up ramp = the largest single upward step.
            jmax = max(range(len(steps)), key=lambda i: steps[i])
            op = series[jmax + 1:]           # operating window (post-ramp)
            if len(op) < 3:
                self.finding("note", "I-2",
                             f"{name}: warm-up ramp at checkpoint {jmax + 1} leaves "
                             f"only {len(op)} operating-window point(s) — "
                             f"inconclusive, run a larger op budget")
                return
            delta = op[-1] - op[0]
            ups = sum(1 for i in range(len(op) - 1) if op[i + 1] > op[i] + 1)
            frac_up = ups / (len(op) - 1)
            if delta > budget and frac_up >= 0.5:
                monotonic = all(op[i + 1] >= op[i] - 1 for i in range(len(op) - 1))
                confirmed = monotonic and delta > 2 * budget
                sev = "leak" if confirmed else "suspected"
                tail = "" if confirmed else " — SUSPECTED, needs longer-run confirmation"
                self.finding(sev, "I-2",
                             f"{name} rose {op[0]:.0f}->{op[-1]:.0f}{unit} across the "
                             f"operating window (post warm-up ramp at cp{jmax + 1}; "
                             f"+{delta:.0f}, {int(frac_up * 100)}% of steps up){tail}")

        trend([c["handles"] for c in self.checkpoints], 150, "handle count", "")
        trend([c["rss_mb"] for c in self.checkpoints], 200, "RSS", "MB")
        trend([c["threads"] for c in self.checkpoints], 15, "thread count", "")

    # ---- I-3 undo reversible probe -------------------------------------

    def undo_probe(self) -> None:
        """Insert a blank page, confirm the count rose, undo, confirm it
        returns. A divergence is an I-3 finding."""
        before = self.query_page_count()
        if before is None:
            return
        if not self.activate("insertBlankPageAction"):
            return
        time.sleep(0.5)
        after = self.query_page_count()
        if after is None or after <= before:
            # Insert did not take — not an undo defect; skip the undo half.
            return
        self.page_count = after
        self.activate("undoAction")
        time.sleep(0.5)
        restored = self.query_page_count()
        if restored != before:
            self.finding("undo", "I-3",
                         f"page count did not return after undo: "
                         f"{before}->{after}->{restored}")
        else:
            self.page_count = before

    # ---- I-4 / I-5 save-reopen integrity -------------------------------

    def save_reopen_integrity(self, tag: str) -> None:
        saved = RUNTIME / f"journey_{self.target}_{tag}.pdf"
        if not self.save_as(saved):
            if not self.alive():
                self.finding("crash", "I-1", f"process died during save '{tag}'")
                raise _JourneyCrash(f"save-{tag}")
            # gap-A14: the save pipe may have been undrivable because PDFE's UIA
            # accessibility provider is WEDGED (it stops answering FindAll while
            # PDFE stays alive + WM_NULL-responsive). That is a harness/platform
            # limitation, NOT a product lost-change — the save simply never
            # triggered. Reporting it as a blocking I-4 would be a false
            # positive, and continuing to drive an unresponsive UI just produces
            # more of them. Record an honest inconclusive note and stop.
            from tests.helpers import qinvoke  # noqa: PLC0415
            if qinvoke.is_uia_wedged(self.s):
                self.finding("note", "gap-A14",
                             f"UIA provider wedged at save '{tag}'; could not "
                             f"drive the save. Journey inconclusive from here "
                             f"(harness/platform limitation — PDFE remained "
                             f"alive and responsive to Win32 messages, not a "
                             f"product defect).")
                raise _JourneyWedge(f"wedge-{tag}")
            self.finding("lost-change", "I-4",
                         f"save pipe produced no file at '{tag}'")
            return
        # Reopen with an independent reader (PyMuPDF) — proves the on-disk file
        # is not corrupt and reopens without error (I-4), and lets us confirm
        # edited content is present rather than a stale pre-edit rendering (I-5).
        import fitz
        try:
            doc = fitz.open(str(saved))
        except Exception as exc:  # noqa: BLE001
            self.finding("corruption", "I-4",
                         f"saved file failed to reopen at '{tag}': {exc!r}")
            return
        try:
            pc = doc.page_count
            if pc < 1:
                self.finding("corruption", "I-4",
                             f"reopened file has {pc} pages at '{tag}'")
            # Structure sanity: every page must load + extract without throwing.
            bad = 0
            for i in range(pc):
                try:
                    doc.load_page(i).get_text("text")
                except Exception:  # noqa: BLE001
                    bad += 1
            if bad:
                self.finding("corruption", "I-4",
                             f"{bad}/{pc} pages failed to extract from the "
                             f"reopened file at '{tag}'")
        finally:
            doc.close()
        print(f"  I-4 save/reopen OK '{tag}': {saved.name} "
              f"({saved.stat().st_size} bytes)")


class _JourneyWedge(Exception):
    """Raised to stop the journey when PDFE's UIA provider wedges (gap-A14): the
    harness can no longer drive/observe the UI, so the run is inconclusive from
    that point. Recorded as a non-blocking note, not a product defect."""


class _JourneyCrash(Exception):
    """Raised to stop the journey immediately when I-1 fails."""


