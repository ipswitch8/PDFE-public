# The journey
# ---------------------------------------------------------------------------

def _run_journey(target_name: str, src: Path) -> JourneyDriver:
    from tests.helpers.pdfe_session import PDFESession, no_orphans

    RUNTIME.mkdir(parents=True, exist_ok=True)
    work = RUNTIME / f"journey_{target_name}_working.pdf"
    shutil.copy2(src, work)

    with PDFESession(pdf_path=str(work)) as s:
        assert s.wait_for_window_title("PDFE"), "PDFE window never appeared"
        s.wait_for_idle()
        time.sleep(1.0)

        pc = None
        try:
            from tests.helpers import qinvoke
            qinvoke._write_to_pipe(s, "testPageCountQueryPipe", "1", settle=0.2)
            raw = qinvoke._read_result_pipe(s, "testPageCountResultPipe")
            pc = int((raw or "").strip())
        except Exception:  # noqa: BLE001
            pc = None

        d = JourneyDriver(s, target_name, pc or 3)
        print(f"\n=== journey '{target_name}' pages={d.page_count} "
              f"budget={OP_BUDGET} batch={BATCH} ===")
        d.checkpoint("open")

        try:
            batch_no = 0
            while d.op_count < OP_BUDGET:
                batch_no += 1
                batch_start = d.op_count
                i = 0
                while d.op_count < OP_BUDGET and (d.op_count - batch_start) < BATCH:
                    step = (batch_no * 7 + i)
                    # Diverse, deterministic op mix drawn from the FULL
                    # AC1 vocabulary (annotate/move/delete, redact, rotate/
                    # delete page, navigate, scroll, zoom).
                    kind = step % 13
                    page = (step * 3) % d.page_count
                    if kind == 0:
                        d.create_annot(page, step)          # dirties + refreshAllPages
                    elif kind == 1:
                        d.scroll_whole_document()           # B-1 trigger half
                    elif kind == 2:
                        d.goto(page)
                    elif kind == 3:
                        d.create_annot(page, step + 1)
                        d.scroll_whole_document()           # armed edit -> scroll
                    elif kind == 4:
                        d.add_redaction(page)               # redact
                    elif kind == 5:
                        d.activate("actionRotateViewCW")    # rotate VIEW
                        d.scroll(700)
                    elif kind == 6:
                        d.goto((page + 7) % d.page_count)
                        d.create_annot((page + 1) % d.page_count, step)
                    elif kind == 7:
                        d.activate("zoomInAction")
                        d.scroll_whole_document()
                        d.activate("zoomOutAction")
                    elif kind == 8:
                        d.move_annot()                      # move annotation
                    elif kind == 9:
                        d.delete_annot()                    # delete annotation
                    elif kind == 10:
                        d.rotate_page(page, cw=(step % 2 == 0))  # rotate PAGE
                    elif kind == 11:
                        d.delete_page(page)                 # delete page (guarded)
                    else:
                        d.small_text_edit(page)             # direct small-text edit (#4/#5 path)
                    i += 1

                # Hunt B-1 explicitly once per batch with a zero-settle
                # edit->scroll burst (the polite batch ops above settle too
                # long to open the UAF window).
                d.armed_race_burst(rounds=8)

                d.checkpoint(f"batch{batch_no}")

                # Rotating deeper oracles so each fires several times across
                # the journey without exploding the op budget.
                if batch_no % 3 == 1:
                    d.undo_probe()                          # I-3 single-step
                    d.checkpoint(f"batch{batch_no}-postundo")
                if batch_no % 3 == 2:
                    d.deep_undo_redo(k=5)                   # deep undo/redo chain
                    d.checkpoint(f"batch{batch_no}-postdeepundo")
                if batch_no % 2 == 0:
                    d.replace_all("the", "THE")             # #6 all-page extract
                    d.checkpoint(f"batch{batch_no}-postreplace")
                    d.save_reopen_integrity(f"b{batch_no}") # I-4 / I-5

            # Final integrity gate after the whole journey.
            d.save_reopen_integrity("final")
            d.checkpoint("final")
            d.assert_resource_bounded()
        except _JourneyCrash:
            pass  # finding already recorded; fall through to report
        except _JourneyWedge:
            pass  # UIA-wedge note recorded; inconclusive, fall through to report

    # Out of session — persist the findings report.
    RUNTIME.mkdir(parents=True, exist_ok=True)
    report = RUNTIME / f"journey_findings_{target_name}.json"
    with open(report, "w", encoding="utf-8") as f:
        json.dump({
            "target": target_name,
            "source": str(src),
            "op_budget": OP_BUDGET,
            "batch": BATCH,
            "ops_performed": d.op_count,
            "checkpoints": d.checkpoints,
            "findings": d.findings,
        }, f, indent=2)
    print(f"=== findings report: {report} "
          f"({len(d.findings)} findings, {d.op_count} ops) ===")

    assert no_orphans(), "orphaned pdfe.exe after the journey"
    return d


def _targets():
    # Env override: journey against every *.pdf in JOURNEY_TARGET_DIR, exactly
    # that set (soak an arbitrary document collection — one parametrized case
    # per file). Default behaviour (built-in corpus + SpecimenA-if-present) is
    # unchanged when the var is unset, so CI is unaffected.
    tdir = os.environ.get("JOURNEY_TARGET_DIR")
    if tdir and Path(tdir).is_dir():
        out = []
        seen = set()
        for p in sorted(Path(tdir).glob("*.pdf")):
            base = "".join(c if c.isalnum() else "_"
                           for c in p.stem).strip("_").lower()[:40] or "pdf"
            name, i = base, 2
            while name in seen:
                name, i = f"{base}_{i}", i + 1
            seen.add(name)
            out.append((name, p))
        if out:
            return out
    out = [("corpus", CORPUS)]
    k = _find_specimen_a()
    if k is not None:
        out.append(("specimen_a", k))
    return out


@pytest.mark.parametrize("target_name,src", _targets())
def test_cumulative_single_session_journey(target_name, src):
    """The document survives a long, diverse single-session journey with all
    cumulative invariants intact. Any crash (I-1), corruption / lost change
    (I-4), unbounded leak (I-2), undo divergence (I-3), or stale-tile defect
    (I-5) surfaces as a severity-ranked finding and fails the test."""
    d = _run_journey(target_name, src)

    # 'note' and 'suspected' are REPORTED but do not fail the test: a suspected
    # signal (e.g. RSS growth that may be bounded working-set churn) is a
    # Phase-3 investigation item, not a confirmed defect. Only confirmed
    # cumulative defects fail.
    reported = [f for f in d.findings if f["severity"] in ("note", "suspected")]
    for f in reported:
        print(f"  [REPORTED {f['severity']}/{f['invariant']}] "
              f"op={f['op_count']}: {f['detail']}")

    blocking = [f for f in d.findings
                if f["severity"] not in ("note", "suspected")]
    if blocking:
        # Rank most-severe first for the failure message.
        order = {"crash": 0, "corruption": 1, "lost-change": 2,
                 "leak": 3, "undo": 4, "stale-tile": 5}
        blocking.sort(key=lambda f: order.get(f["severity"], 9))
        lines = "\n".join(
            f"  [{f['severity']}/{f['invariant']}] op={f['op_count']}: {f['detail']}"
            for f in blocking)
        pytest.fail(
            f"journey '{target_name}' found {len(blocking)} confirmed cumulative "
            f"single-session defect(s):\n{lines}")
