class ContentStreamEditorTest : public ::testing::Test {
protected:
    void SetUp() override {
        context = std::make_shared<MuPdfContext>();
        std::filesystem::path fixturesDir = TEST_FIXTURES_DIR;
        pdfPath = fixturesDir / "test_3page.pdf";
        if (!std::filesystem::exists(pdfPath)) {
            GTEST_SKIP() << "test_3page.pdf not available";
        }
        document = Document::open(context, pdfPath);
    }

    void TearDown() override {
        document.reset();
        context.reset();
    }

    // Helper: collect all spans from a TextEditModel
    std::vector<TextSpan> collectSpans(const TextEditModel& model) {
        std::vector<TextSpan> result;
        for (int i = 0; i < model.spanCount(); ++i) {
            result.push_back(model.span(i));
        }
        return result;
    }

    // ---- A1-41 helpers: real neighbour-preservation oracle ----------------

    /// AUTHORED ground truth for page 0 of tests/fixtures/test_3page.pdf,
    /// copied verbatim from tests/generate_fixtures.py::generate_3page_pdf.
    /// Expectations are anchored to these literals, never to current output.
    static const std::vector<std::string>& authoredPage1Lines() {
        static const std::vector<std::string> lines = {
            "Page 1 - Title Page",
            "This is a test PDF for PDFE unit tests.",
            "Generated by generate_fixtures.py",
        };
        return lines;
    }

    static std::string u32ToUtf8(const std::u32string& s) {
        std::string out;
        for (char32_t cp : s) {
            if (cp < 0x80) {
                out.push_back(static_cast<char>(cp));
            } else if (cp < 0x800) {
                out.push_back(static_cast<char>(0xC0 | (cp >> 6)));
                out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
            } else if (cp < 0x10000) {
                out.push_back(static_cast<char>(0xE0 | (cp >> 12)));
                out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
                out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
            } else {
                out.push_back(static_cast<char>(0xF0 | (cp >> 18)));
                out.push_back(static_cast<char>(0x80 | ((cp >> 12) & 0x3F)));
                out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
                out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
            }
        }
        return out;
    }

    static int countOccurrences(const std::string& hay,
                                const std::string& needle) {
        if (needle.empty()) return 0;
        int n = 0;
        for (std::size_t p = hay.find(needle); p != std::string::npos;
             p = hay.find(needle, p + needle.size()))
            ++n;
        return n;
    }

    static bool isBlank(const std::string& s) {
        for (unsigned char c : s)
            if (c != ' ' && c != '\t' && c != '\n' && c != '\r')
                return false;
        return true;
    }

    /// A single extracted text line: its exact text and where it sits.
    /// Lines (not spans) are the stable unit across a content-stream
    /// rewrite, so neighbour "unmoved" checks are made at line granularity.
    struct LineSnapshot {
        std::string text;
        QRectF box;
    };

    static std::vector<LineSnapshot> snapshotLines(Page* page) {
        std::vector<LineSnapshot> out;
        for (const auto& block : page->extractText())
            for (const auto& line : block.lines)
                out.push_back({line.text(), line.boundingBox});
        return out;
    }

    /// True when some line in @p after has exactly @p text and its top-left
    /// corner is within @p tol points of @p box.
    static bool hasUnmovedLine(const std::vector<LineSnapshot>& after,
                               const std::string& text,
                               const QRectF& box, double tol) {
        for (const auto& l : after) {
            if (l.text != text) continue;
            if (std::abs(l.box.left() - box.left()) <= tol &&
                std::abs(l.box.top() - box.top()) <= tol)
                return true;
        }
        return false;
    }

    std::shared_ptr<MuPdfContext> context;
    std::filesystem::path pdfPath;
    std::unique_ptr<Document> document;
};

