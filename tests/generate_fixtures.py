    generate_3page_pdf(os.path.join(fixtures_dir, "test_3page.pdf"))
    generate_single_page_pdf(os.path.join(fixtures_dir, "test_single.pdf"))
    generate_landscape_pdf(os.path.join(fixtures_dir, "test_landscape.pdf"))
    generate_multisize_pdf(os.path.join(fixtures_dir, "test_multisize.pdf"))
    generate_multispan_pdf(os.path.join(fixtures_dir, "test_multispan.pdf"))

    print("\nAll test fixtures generated successfully.")
