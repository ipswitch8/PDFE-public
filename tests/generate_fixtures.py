def generate_multisize_pdf(output_path: str) -> None:
    """Generate a PDF with different page sizes."""
    pdf = FPDF()
    pdf.set_auto_page_break(auto=False)

    # Page 1: Letter (default 215.9 x 279.4 mm)
    pdf.add_page()
    pdf.set_font("Helvetica", "", 14)
    pdf.cell(0, 20, "Letter size page (8.5 x 11 in)", new_x="LMARGIN", new_y="NEXT", align="C")

    # Page 2: A4 (210 x 297 mm)
    pdf.add_page(format="A4")
    pdf.cell(0, 20, "A4 size page (210 x 297 mm)", new_x="LMARGIN", new_y="NEXT", align="C")

    # Page 3: Legal (215.9 x 355.6 mm)
    pdf.add_page(format="legal")
    pdf.cell(0, 20, "Legal size page (8.5 x 14 in)", new_x="LMARGIN", new_y="NEXT", align="C")

    pdf.output(output_path)
    print(f"Generated: {output_path}")


def generate_multispan_pdf(output_path: str) -> None:
    """Generate a single-page PDF with multiple distinct text spans.

    Creates 4 text spans at known positions with different fonts/sizes,
    suitable for testing multi-span text editing operations.
    """
    pdf = FPDF()
    pdf.add_page()

    # Span 1: Title in bold 18pt
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_xy(50, 50)
    pdf.cell(0, 15, "First Span Title", new_x="LMARGIN", new_y="NEXT")

    # Span 2: Body text in regular 12pt
    pdf.set_font("Helvetica", "", 12)
    pdf.set_xy(50, 80)
    pdf.cell(0, 10, "Second span body text here", new_x="LMARGIN", new_y="NEXT")

    # Span 3: Different position, same font
    pdf.set_xy(50, 110)
    pdf.cell(0, 10, "Third span more content", new_x="LMARGIN", new_y="NEXT")

    # Span 4: Courier font, different size
    pdf.set_font("Courier", "", 10)
    pdf.set_xy(50, 140)
    pdf.cell(0, 10, "Fourth span in Courier", new_x="LMARGIN", new_y="NEXT")

    pdf.output(output_path)
    print(f"Generated: {output_path}")


