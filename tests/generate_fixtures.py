# -*- coding: utf-8 -*-
"""Generate test PDF fixtures for PDFE unit tests."""

import os
import sys

# Ensure UTF-8 output
sys.stdout.reconfigure(encoding='utf-8')

from fpdf import FPDF


def generate_3page_pdf(output_path: str) -> None:
    """Generate a simple 3-page PDF with text content."""
    pdf = FPDF()
    pdf.set_auto_page_break(auto=False)

    # Page 1: Letter size, portrait
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 24)
    pdf.cell(0, 20, "Page 1 - Title Page", new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.set_font("Helvetica", "", 12)
    pdf.cell(0, 10, "This is a test PDF for PDFE unit tests.", new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.cell(0, 10, "Generated by generate_fixtures.py", new_x="LMARGIN", new_y="NEXT", align="C")

    # Page 2: Some body text
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 15, "Page 2 - Body Content", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    text = (
        "Lorem ipsum dolor sit amet, consectetur adipiscing elit. "
        "Sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. "
        "Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris "
        "nisi ut aliquip ex ea commodo consequat. Duis aute irure dolor in "
        "reprehenderit in voluptate velit esse cillum dolore eu fugiat nulla pariatur."
    )
    pdf.multi_cell(0, 6, text)

    # Page 3: Mixed content
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 15, "Page 3 - Final Page", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(0, 8, "Item 1: First list item", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, "Item 2: Second list item", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, "Item 3: Third list item", new_x="LMARGIN", new_y="NEXT")
    # Draw a rectangle
    pdf.rect(50, 100, 100, 60)
    pdf.set_xy(60, 120)
    pdf.cell(80, 10, "Rectangle with text", align="C")

    pdf.output(output_path)
    print(f"Generated: {output_path}")


