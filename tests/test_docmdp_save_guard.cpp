// -*- coding: utf-8 -*-
//
// Meta-audit 2026-07 follow-up, phase F24 — item 1: DocMDP was detection with
// no consumer.
//
// F2 built DocMdpEnforcer (the read side of /Perms /DocMDP) and F21 made it
// correct on the ISO 32000-1 §12.8.2.2 layout Acrobat and pyHanko emit. Neither
// wired it to anything: `grep -rn "checkDocMdp|DocMdpEnforcer" src/` returned
// the class, its CMake entry and a friend declaration — no call site. A
// P1-certified ("no changes permitted") document could therefore be edited and
// saved by PDFE with nothing objecting.
//
// The consumer is src/signatures/DocMdpSaveGuard.cpp, installed into
// pdfe::core::Document's save path (src/ui/MainWindow.cpp, constructor). These
// tests exercise it THROUGH THE REAL SAVE PATH — Document::save() and
// Document::saveAs() — not by asking the classifier a question.
//
// THE PRODUCT DECISION under test (recorded in phase-24-dispositions.md §1):
//   * in-place save of a certified original whose certification the pending
//     change breaks  -> REFUSED, nothing written;
//   * Save As to a different path                          -> ALLOWED, warned.
// A desktop editor that refuses every route to disk strands the user's work;
// one that silently overwrites a certified original destroys a tamper-evident
// artifact. Splitting on the target avoids both.
//
// THE DISCRIMINATING CONTROL, without which this would be an indiscriminate
// block on certified documents rather than a /P-aware control: the SAME change
// (add an annotation), applied to a /P 3 document where ISO 32000-1 Table 254
// permits annotations, must save in place without objection.
//
// Fixtures: tests/fixtures/sig_iso_docmdp_p1.pdf and sig_iso_docmdp_p3.pdf,
// generated by tests/fixtures/gen_sig_shadow_corpus.py. They are identical
// except for the /P value inside /Reference /TransformParams, so nothing but
// the certification level can explain a difference in outcome.

